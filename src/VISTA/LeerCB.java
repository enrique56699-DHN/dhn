    private void funcion() throws ClassNotFoundException, SQLException, Exception
    {
        String CB = txtCB.getText();
        
        ModeloProductosD mdl;
        ControlProductosD ctrl = new ControlProductosD();
        mdl = ctrl.getRegistroID("CB",CB);
        if(mdl != null)
        {
            JOptionPane.showMessageDialog(null, mdl.getDESCRIPCION()+"\n"+"Precio Publico: "+mdl.getPP()+"\n"+"Precio Instalador: "+mdl.getPI(), mdl.getSICAR(), JOptionPane.INFORMATION_MESSAGE);
            clipboard(mdl.getSICAR());
        }
        else
            JOptionPane.showMessageDialog( null, "El codigo no esta relacionado a ningun producto", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    
    }
    
    private void clipboard(String SICAR)
    {
        StringSelection selection = new StringSelection(SICAR);
        Clipboard clipboard = Toolkit.getDefaultToolkit().getSystemClipboard();
        clipboard.setContents(selection, selection);
    }

