    public void mostrar(int IDECONTACTO, int IDEMPLEADO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDECONTACTO = IDECONTACTO;
        this.IDEMPLEADO = IDEMPLEADO;
        
        switch(ACCION)
        {
            case "NUEVO":
                this.txtNOMBRE.requestFocus();
                break;                
            case "EDITAR":
                ModeloEContactos mdl;
                ControlEContactos ctrl = new ControlEContactos();
                mdl=ctrl.getRegistrosID(IDECONTACTO);                
                this.txtID.setText(""+this.IDECONTACTO);
                this.txtNOMBRE.setText(""+mdl.getNOMBRE());
                this.txtTEL.setText(""+mdl.getTEL());
                this.txtEMAIL.setText(""+mdl.getEMAIL());                             
                break;                
            default:
                break;
        }
       this.txtNOMBRE.requestFocus();
    }
     

    private void guardar(String ACCION)
    {                                                      
        ModeloEContactos mod = new ModeloEContactos();

        mod.setIDECONTACTO(IDECONTACTO);
        mod.setIDEMPLEADO(IDEMPLEADO);
        mod.setNOMBRE(txtNOMBRE.getText());
        mod.setTEL(txtTEL.getText());
        mod.setEMAIL(txtEMAIL.getText());

        switch(ACCION)
        {
            case "NUEVO":
                try
                {
                    IDECONTACTO = F.Registro("ECONTACTOS","IDECONTACTO","DESC");
                    mod.setIDECONTACTO(IDECONTACTO);

                    ControlEContactos cp = new ControlEContactos();
                    cp.guardarRegistro(mod);
                    this.dispose();                    
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    ControlEContactos cp = new ControlEContactos();
                    cp.actualizarRegistro(mod);
                    this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }   
        
    }
    
