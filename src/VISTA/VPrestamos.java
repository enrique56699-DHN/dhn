    private void permisos(String PRIVILEGIOS)
    {
        if(PRIVILEGIOS.equals("SADMIN"))
        {
            btnEDITAR.setEnabled(true);
            btnBORRAR.setEnabled(true);
        }
    }
    
    private void actualizarTablas() throws ClassNotFoundException, SQLException
    {
        ModeloPrestamosTabla met;
        met = new ModeloPrestamosTabla();
        jtblPRESTAMOS.setModel(met);
        F.dimensionar(jtblPRESTAMOS,"PRESTAMOS");
    }

    private void editar() throws ClassNotFoundException, SQLException, Exception
    {
        try
           {
               RegPrestamos p = new RegPrestamos(null,true);
               p.accion(IDPRESTAMO, 0, "EDITAR");
               p.setVisible(true);
               actualizarTablas();
        }
        catch (ParseException ex)
        {
            JOptionPane.showMessageDialog( null, "PARA PODER EDITAR UN REGISTRO,\nPRIMERO DEBE SELECCIONAR UNA FILA DE LA TABLA", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
        }
    }
    
    private void seleccion() throws ClassNotFoundException, SQLException, Exception
    {
        int fila = jtblPRESTAMOS.getSelectedRow();
        IDPRESTAMO = (int) jtblPRESTAMOS.getValueAt(fila, 0);
        descripcion = jtblPRESTAMOS.getValueAt(fila, 3).toString();
        monto = jtblPRESTAMOS.getValueAt(fila, 4).toString();
        EMPLEADO = jtblPRESTAMOS.getValueAt(fila, 1).toString();
        FECHA = jtblPRESTAMOS.getValueAt(fila, 2).toString();
    }
    
    private void imprimir() throws IOException, ClassNotFoundException, SQLException
    {
        ImpPRESTAMO pca = new ImpPRESTAMO(FECHA,""+IDPRESTAMO,"$ "+monto,descripcion,EMPLEADO);
        JButton[] opciones = pca.getButtons();

        JOptionPane.showInternalOptionDialog(this, pca, "Imprimir PRESTAMO",JOptionPane.OK_CANCEL_OPTION,-1, null, opciones, opciones[0]);
        if(pca.getOpcion() != null)
            pca.Imprimir();                     
    }

