    public void mostrar(int IDEXTRA, String ACCION, String TIPO) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        switch(ACCION)
        {
            case "NUEVO":
                this.txtDESCRIPCION.requestFocus();
                this.cmbTIPO.setSelectedItem(TIPO);
                this.cmbTIPO.setEnabled(false);
                break;
            case "EDITAR":
                ModeloExtras mdl;
                ControlExtras ctrl = new ControlExtras();
                mdl=ctrl.getRegistrosID(IDEXTRA);                
                this.txtIDEXTRA.setText(""+mdl.getIDEXTRA());
                this.txtDESCRIPCION.setText(""+mdl.getDESCRIPCION());
                this.txtMONTO.setText(""+mdl.getMONTO());
                this.dteFECHA.setDate(G.formato.parse(mdl.getFECHA()));
                this.cmbTIPO.setSelectedItem(mdl.getTIPO());
                break;
            default:
                break;
        }        
    }
    
    private void guardar(String ACCION)
    {
        if(this.txtDESCRIPCION.getText().equals(""))
        {
            JOptionPane.showMessageDialog( null, "CAMPO NO PUEDE ESTAR VACIO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
            this.txtDESCRIPCION.requestFocus();
        }
        else
        {
            ModeloExtras mdl = new ModeloExtras();

            mdl.setFECHA(G.FECHA(dteFECHA.getDate(),true));
            mdl.setDESCRIPCION(txtDESCRIPCION.getText());
            mdl.setTIPO(cmbTIPO.getSelectedItem().toString());
            mdl.setMONTO(Float.parseFloat(txtMONTO.getText()));
            //monto = Float.parseFloat(txtMONTO.getText());

            switch(ACCION)
            {
                case "NUEVO":
                    try
                    {
                        IDEXTRA = F.Registro("EXTRAS","IDEXTRA","DESC");
                        mdl.setIDEXTRA(IDEXTRA);
                        //System.out.println("aqui toy");
                        ControlExtras cp = new ControlExtras();
                        cp.guardarRegistro(mdl);                            
                        APOYO();
                        this.dispose();
                    }
                    catch (Exception ex)
                    {

                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO ", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        System.out.println(ex);
                    }
                    break;
                case "EDITAR":
                    try
                    {
                        mdl.setIDEXTRA(Integer.parseInt(txtIDEXTRA.getText()));

                        ControlExtras cp = new ControlExtras();
                        cp.actualizarRegistro(mdl);
                        APOYO();
                        this.dispose();
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                default:
                    break;
            }
        }        
    }
    
    private void APOYO() throws SQLException, Exception
    {
        JInternalFrame ji = validador.getJInternalFrame(VApoyo.class.getName());      
        if(ji != null )
            ji.dispose();
        ji = new VApoyo("EXTRAS",G.formato.format(dteFECHA.getDate()),
                ""+IDEXTRA,
                ""+G.numero.format(Float.parseFloat(txtMONTO.getText()))+".00",
                txtDESCRIPCION.getText(),
                cmbTIPO.getSelectedItem().toString());
        Principal.getCONT().add(ji);
        validador.addJIframe(VApoyo.class.getName(), ji);
        RegExtras.btnCERRAR.doClick();
        this.dispose();
              
        ji.setMaximum(true);        
    }
    
