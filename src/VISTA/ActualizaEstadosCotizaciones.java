    public void mostrar(int IDCOTIZACION, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDCOTIZACION = IDCOTIZACION;
        switch(ACCION)
        {
            case "NUEVO":                
                break;
            case "EDITAR":
                ModeloCotizaciones mdl;
                ControlCotizaciones ctrl = new ControlCotizaciones();
                mdl = ctrl.getRegistro("IDCOTIZACION", IDCOTIZACION, "");
                IDPENDIENTE = mdl.getIDPENDIENTE();
                txtESTADO.setSelectedItem(mdl.getESTADO());
                this.txtESTADO.requestFocus();
                break;
            default:
                break;
        }
    }
    
    private void guardar(String ACCION) throws Exception
    {                
        switch(ACCION)
        {
            case "NUEVO":                
                break;
            case "EDITAR":
                try
                {
                    F.actualizarRegistro("COTIZACIONES", "ESTADO", 0, txtESTADO.getSelectedItem().toString(), "IDCOTIZACION", IDCOTIZACION, "");
                    F.bitacora("COTIZACIONES", IDCOTIZACION, ACCION, G.IDUSER, txtCOMENTARIOS.getText().trim(), "");
                    //this.dispose();
                    if(txtESTADO.getSelectedItem().toString().equals("APROBADA"))
                    {
                        ModeloPendientes mdl;
                        ControlPendientes ctrl = new ControlPendientes();
                        mdl = ctrl.getRegistroID(IDPENDIENTE);
                        String DESCRIPCION = mdl.getDESCRIPCION();
                        DESCRIPCION = DESCRIPCION +"\n"+
                                " PROYECTO HABILITADO POR APROBACION DE COTIZACION N. "+IDCOTIZACION;                        
                        F.actualizarRegistro("PENDIENTES", "DESCRIPCION", 0,DESCRIPCION , "IDPENDIENTE",IDPENDIENTE ,"" );
                    }
                    
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }
    } 
    
    
