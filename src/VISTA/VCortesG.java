    private void actualizarTablas() throws ClassNotFoundException, SQLException
    {
        ModeloCortesGlobalTabla met;
        met = new ModeloCortesGlobalTabla();
        tblCORTES.setModel(met);
        F.dimensionar(tblCORTES,"CORTESG");
    }

    private void seleccion() throws ClassNotFoundException, SQLException, Exception
    {
        int fila = tblCORTES.getSelectedRow();
        IDCORTEG = (int) tblCORTES.getValueAt(fila, 0);
    }
    
    private void imprimir() throws ClassNotFoundException, SQLException, Exception
    {
        ModeloCortesGlobal mdl;
        ControlCortesGlobal ctrl = new ControlCortesGlobal();
        mdl=ctrl.getRegistroID(IDCORTEG);
                
        ImpCorteDIAG pca = new ImpCorteDIAG(mdl.getFECHA(),""+mdl.getIDCORTEG(),
                "$ "+G.numero.format(mdl.getEDH()), "$ "+G.numero.format(mdl.getDHN()), "$ "+G.numero.format(mdl.getVALES()),"$ "+G.numero.format(mdl.getCF()),
                "$ "+G.numero.format(mdl.getMONTOG()),"$ "+G.numero.format(mdl.getMONTOR()));
        JButton[] opciones = pca.getButtons();
        JOptionPane.showInternalOptionDialog(this, pca, "Imprimir Corte de Caja GLOBAL",JOptionPane.OK_CANCEL_OPTION,-1, null, opciones, opciones[0]);
        if(pca.getOpcion() != null)
            pca.Imprimir();        
    }

