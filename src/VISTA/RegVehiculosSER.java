    public void mostrar(int IDVEHICULOSER, int IDVEHICULO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;   
        this.IDVEHICULOSER = IDVEHICULOSER;
        this.IDVEHICULO = IDVEHICULO;
        
        vehiculo(IDVEHICULO);
        
        switch(ACCION)
        {
            case "NUEVO":
                lblIDVEHICULO.setText(""+IDVEHICULO);
                this.txtTIPO.requestFocus();
                break;
            case "EDITAR":
                ModeloVehiculosSER mdl;
                ControlVehiculosSER ctrl = new ControlVehiculosSER();
                mdl=ctrl.getRegistros(IDVEHICULOSER);
                
                this.txtIDVEHICULOSER.setText(""+mdl.getIDVEHICULOSER());
                this.lblIDVEHICULO.setText(""+mdl.getIDVEHICULO());
                this.txtTIPO.setSelectedItem(mdl.getTIPO());
                this.txtCOMENTARIOS.setText(""+mdl.getCOMENTARIOS());
                this.txtKM.setText(""+mdl.getKM());
                this.txtCOSTO.setText(""+mdl.getCOSTO());

                this.dteFECHA.setDate(G.formato.parse(mdl.getFECHA()));
                
                break;
            default: break;
        }
    }
    
    private void vehiculo(int IDVEHICULO) throws ClassNotFoundException, SQLException, Exception
    {
        ModeloVehiculos mdl;
        ControlVehiculos ctrl = new ControlVehiculos();
        mdl=ctrl.getRegistros(IDVEHICULO);        
        
        this.txtEMPRESA.setSelectedItem(""+mdl.getEMPRESA());
        this.lblNOMBRE.setText(mdl.getMARCA()+" "+mdl.getMODELO());
    }
   
    private void guardar(String ACCION) throws Exception
    {
        ModeloVehiculosSER mdl = new ModeloVehiculosSER();

        
        mdl.setIDVEHICULO(IDVEHICULO);
        mdl.setEMPRESA(txtEMPRESA.getSelectedItem().toString());
        mdl.setKM(Integer.parseInt(txtKM.getText()));
        mdl.setCOMENTARIOS(txtCOMENTARIOS.getText());
        mdl.setCOSTO(Float.parseFloat(txtCOSTO.getText()));       
        mdl.setFECHA(""+G.formato.format(dteFECHA.getDate()));    
        mdl.setTIPO(txtTIPO.getSelectedItem().toString());
       
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            
                            ControlVehiculosSER ctrl = new ControlVehiculosSER();
                            ctrl.guardarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {                           
                            mdl.setIDVEHICULOSER(Integer.parseInt(txtIDVEHICULOSER.getText()));
                            ControlVehiculosSER ctrl = new ControlVehiculosSER();
                            ctrl.actualizarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default: break;
                }
        
        
    }    
    
    private void cmb() throws ClassNotFoundException, SQLException
    {
        txtTIPO.removeAllItems();         
        //int NUM = mdlt.getRowCount();
        mdlt = new ModeloDetallesDispTabla(TABLA,"SERVICIOS");
        for(int i=0;i<mdlt.getRowCount();i++)
        {
            txtTIPO.addItem((String) mdlt.getValueAt(i, 0));            
        }        
        
    }
    
    
