    public void mostrar(int IDCONTRATO) throws SQLException, Exception
    {
        ModeloContratos mdl;
        ControlContratos ctrl = new ControlContratos();
        
        mdl = ctrl.getRegistrosIDINNER(IDCONTRATO);
        this.lblNCONTRATO.setText(IDCONTRATO+"");
        this.lblCLIENTE.setText(mdl.getNOMBRE());
        this.lblDOMICILIO.setText(mdl.getCALLE()+" "+mdl.getNUMERO()+" "+mdl.getCOLONIA()+" "+mdl.getLOCALIDAD());
        this.lblDIACORTE.setText(mdl.getFCOR());
        actualizarTablas(IDCONTRATO);
    }
        
    private void actualizarTablas(int IDCONTRATO) throws ClassNotFoundException, SQLException, Exception
    {
        ModeloPagosTabla mtpn;
        mtpn = new ModeloPagosTabla (IDCONTRATO);
        tblTABLA.setModel(mtpn);
        F.dimensionar(tblTABLA,"REGPAGOS");
    }
    
    private void seleccion(JTable tabla) throws ClassNotFoundException, SQLException
    {                
        int fila = tabla.getSelectedRow(); 
        NARCHIVO = (String) tabla.getValueAt(fila, 5);
    }
    
    private void abrir()
    {
        if(NARCHIVO.equals(""))        
            JOptionPane.showMessageDialog( null, "No hay un documento cargado", "VERIFICAR", JOptionPane.WARNING_MESSAGE);        
        else        
            F.abrirArchivo("\\"+"\\"+G.ip+"\\dhn\\VOUCHER\\"+NARCHIVO);        
    }
    
