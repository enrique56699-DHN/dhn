    public void mostrar(int IDENTRADACAJA, String ACCION) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        
        this.ACCION = ACCION;
        
        switch(ACCION)
        {
            case "NUEVO":
                this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.requestFocus();
                break;
            case "EDITAR":
                ModeloEntradasCaja pto;
                ControlEntradasCaja cp = new ControlEntradasCaja();
                pto=cp.getRegistrosID(IDENTRADACAJA);
                
                identradascaja = pto.getIDENTRADACAJA();
                this.txtIDENTRADA.setText(""+pto.getIDENTRADACAJA());
                this.txtDESCRIPCION.setText(""+pto.getDESCRIPCION());
                this.txtMONTO.setText(""+pto.getMONTO());
                this.dte_fecha.setDate(G.formato.parse(pto.getFECHA()));
                break;
            default: break;
        }       
        
    }
    
    private void guardar(String ACCION)
    {        
        if(this.txtDESCRIPCION.getText().equals(""))
        {
             JOptionPane.showMessageDialog( null, "CAMPO NO PUEDE ESTAR VACIO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
             this.txtDESCRIPCION.requestFocus();
        }
        else
        {
            ModeloEntradasCaja md = new ModeloEntradasCaja();

            descripcion=txtDESCRIPCION.getText();
            monto=txtMONTO.getText();
            empresa=txtEMPRESA.getSelectedItem().toString();
            
            md.setIDENTRADACAJA(identradascaja);
            md.setDESCRIPCION(descripcion);
            md.setMONTO(Float.parseFloat(monto.trim()));
            md.setEMPRESA(empresa);
            md.setFECHA(G.formato.format(dte_fecha.getDate()));

            switch(ACCION)
            {
                case "NUEVO":
                    try
                    {
                        identradascaja = F.Registro("ENTRADASCAJA","IDENTRADACAJA","DESC");
                        md.setIDENTRADACAJA(identradascaja);

                        ControlEntradasCaja cp = new ControlEntradasCaja();
                        cp.guardarRegistro(md);
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                    }
                    break;
                case "EDITAR":
                    try
                    {
                        ControlEntradasCaja cp = new ControlEntradasCaja();
                        cp.actualizarRegistro(md);
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                default: break;
            }
        }        
        this.dispose();
    }
    
    
