    public void mostrar(int IDPENDIENTE, int IDORDENP, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.IDPENDIENTE = IDPENDIENTE;
        this.IDORDENP = IDORDENP;
        this.ACCION = ACCION;
        ModeloPendientes mdlP;
        ControlPendientes ctrlP = new ControlPendientes();
        mdlP = ctrlP.getRegistroID(IDPENDIENTE);
        FEST=mdlP.getFEST();        
        if(!FEST.equals(""))        
            this.dteFEST.setDate(G.formato.parse(FEST));       

    }

    private void guardar(String ACCION) throws ClassNotFoundException, SQLException, Exception
    { 
        ControlPendientes ctrlP = new ControlPendientes();
        if(dteFEST.getDate()==null)        
            FEST = "";        
        else                
            FEST= ""+G.formato.format(dteFEST.getDate());
            //FEST= ""+formato.format(dteFEST.getDate());
        ctrlP.actualizarFEST(FEST, IDPENDIENTE);
        switch(ACCION)
        {
            case "AGENDAR":
                break;
            case "IMPORDEN":
                ControlOrdenesP ctrlOP = new ControlOrdenesP();
                ctrlOP.actualizarFINI(FEST, IDORDENP);
                break;
            default:
                break;
        }
        
        this.dispose();
    }
    

