    private void guardar(String ACCION)
    {                                          
        ModeloEDocs mdl = new ModeloEDocs();

        mdl.setIDEDOC(IDEDOC);
        mdl.setIDEMPLEADO(IDEMPLEADO);
        mdl.setNUMBER(txtNUMBER.getText());
        mdl.setDESCRIPCION(txtDESCRIPCION.getSelectedItem().toString());

        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDEDOC = F.Registro("EDOCS", "IDEDOC", "DESC");
                    mdl.setIDEDOC(IDEDOC);
                    
                    ControlEDocs cp = new ControlEDocs();
                    cp.guardarRegistro(mdl);
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    ControlEDocs cp = new ControlEDocs();
                    cp.actualizarRegistro(mdl);
                    this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default: break;

        }          
         
    }
    
    private void selectarchivo() throws IOException
    {        
        File ORIGEN ;
        String DESTINO ;
        JFileChooser se = new JFileChooser();
        se.setFileSelectionMode(JFileChooser.FILES_ONLY);
        int estado = se.showOpenDialog(null);
        if(estado == JFileChooser.APPROVE_OPTION)
        {
            ORIGEN = se.getSelectedFile();
            String ARCHIVO = se.getSelectedFile().getName();
            String EXTENSION = FilenameUtils.getExtension(ARCHIVO);
            String NARCHIVO = lblNOMBRE.getText()+"-"+txtDESCRIPCION.getSelectedItem().toString()+"."+EXTENSION;
            lblARCHIVO.setText(NARCHIVO);
            DESTINO = "\\"+"\\"+G.ip+"\\dhn\\EDOCS\\"+NARCHIVO;
            //DESTINO = "C:\\BST\\PAGOSP\\"+NARCHIVO;
            File DOCUMENTO = new File (DESTINO);
            //copiar(ORIGEN,DESTINO);
            FileUtils.copyFile(ORIGEN, DOCUMENTO);
        }
        
    }

