    private void permisos(String PRIVILEGIOS)
    {
        if(PRIVILEGIOS.equals("SADMIN"))
        {
            btnEDITAR.setEnabled(true);        
        }
    }
    private void editar() throws Exception
    {
        SelectEquipo p = new SelectEquipo(null,true);
        p.mostrar(IDCONTRATO);
        p.setVisible(true);        
    }
    
    private void actualizarTablas() throws ClassNotFoundException, SQLException, Exception
    {
        ModeloContratosTabla mtc;
        mtc = new ModeloContratosTabla(0, "ACTIVO");
        tblCONTRATOS.setModel(mtc);        
        mtc.fireTableDataChanged();
        F.dimensionar(tblCONTRATOS,"CONTRATOSIP");
        this.lblCANTIDAD.setText(""+tblCONTRATOS.getRowCount());
    }
    
    private void seleccion() throws ClassNotFoundException, SQLException
    {
        int fila = tblCONTRATOS.getSelectedRow();
        IDCONTRATO = (int) tblCONTRATOS.getValueAt(fila, 0);             
    }
    
