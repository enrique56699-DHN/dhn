    private void calcula() throws SQLException, Exception 
    {
        if (chkIVA.isSelected()) {
            TCIVA(); 
        } else {
            IVA = 1; 
        }

        // Si la caja de costo está vacía, no tiene sentido calcular nada. Salimos del método.
        if (txtCOSTO.getText().trim().isEmpty()) {
            return; 
        }

        // 1. Corregido: Convertimos a float para no perder los decimales en la división
        float gpCalculado = Float.parseFloat(txtGP.getText()) / 100f;
        float giCalculado = Float.parseFloat(txtGI.getText()) / 100f;

        porcentGP = gpCalculado + 1;           
        porcentGI = giCalculado + 1;

        costo = Float.parseFloat(txtCOSTO.getText());           

        // 2. Optimización: Sacamos las operaciones repetidas fuera del switch
        // El cálculo base para MXN es el mismo, para USD solo se le multiplica el TC (Tipo de Cambio)
        float factorMoneda = 1f;

        switch (txtMONEDA.getSelectedItem().toString()) {
            case "MXN":
                factorMoneda = 1f;
                break;

            case "USD":
                factorMoneda = (float) TC; // Usa el Tipo de Cambio asignado globalmente
                break;

            default:
                return; // Si no es una moneda válida, no calcula nada
        }

        // 3. Procesamos los cálculos finales una sola vez usando el factor de la moneda
        PP = costo * IVA * factorMoneda * porcentGP;
        PP = F.redondearAlCinco(PP);
        lblPPS.setText(String.valueOf(PP));
        txtPP.setText(String.valueOf(PP));

        PI = costo * IVA * factorMoneda * porcentGI;
        PI = F.redondearAlCinco(PI);
        lblPIS.setText(String.valueOf(PI));                
        txtPI.setText(String.valueOf(PI));     
    }
    
    private void guardar(String ACCION)
    {                          
        ModeloProductos mdl = new ModeloProductos();
        
        mdl.setSICAR(txtSICAR.getText());
        mdl.setCATEGORIA(txtCATEGORIA.getSelectedItem().toString());
        mdl.setDESCRIPCION(txtDESCRIPCION.getText().toUpperCase());
        mdl.setCOSTO(Double.parseDouble(txtCOSTO.getText()));
        mdl.setMONEDA(txtMONEDA.getSelectedItem().toString());
        mdl.setIVA(chkIVA.isSelected());
        mdl.setPP(Double.parseDouble(txtPP.getText()));
        mdl.setPI(Double.parseDouble(txtPI.getText()));       
        mdl.setKIT("");             
        
        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDPRODUCTO = F.Registro("PRODUCTOS","IDPRODUCTO","DESC");
                    mdl.setIDPRODUCTO(IDPRODUCTO);
                    
                    ControlProductos ctrl = new ControlProductos();
                    ctrl.guardarRegistro(mdl);                    
                    
                    //this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {                    
                    mdl.setIDPRODUCTO(Integer.parseInt(txtIDPROD.getText()));                   
                    
                    ControlProductos ctrl = new ControlProductos();
                    ctrl.actualizarRegistro(mdl);                   
                    
                    //this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;                        
        }
        
        if(!txtCB.getText().equals("")||!txtCB.getText().equals(null))
        {
            ModeloProductosD mdlD = new ModeloProductosD();
        
            mdlD.setCB(txtCB.getText());
            mdlD.setIDPRODUCTO(IDPRODUCTO);
            mdlD.setCLAVESAT(txtCLAVESAT.getText());
            mdlD.setINVENTARIO(0);
            mdlD.setESTADO(txtESTADO.getSelectedItem().toString());
            mdlD.setMARCA(cmbMARCA.getSelectedItem().toString());
            mdlD.setPROVEEDOR(cmbPROVEEDOR.getSelectedItem().toString());
            mdlD.setSKU(txtSKU.getText());
            mdlD.setCPP(chkPP.isSelected());
            mdlD.setCPI(chkPI.isSelected());
            if(!lblARCHIVO2.getText().equals("Arrasta y Suelta"))
                mdlD.setFOTO(lblARCHIVO2.getText());
            else
                mdlD.setFOTO(null);
            
            switch(ACCION)
            {
                case "NUEVO":
                    try
                    {
                        ControlProductosD ctrlD = new ControlProductosD();
                        ctrlD.guardarRegistroD(mdlD);
                        this.dispose();
                    }
                    catch (Exception ex) 
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                case "EDITAR":
                    try
                    {
                        mdlD.setIDPRODUCTO(Integer.parseInt(txtIDPROD.getText()));
                         
                        ControlProductosD ctrlD = new ControlProductosD();
                        if(D==false)
                            ctrlD.guardarRegistroD(mdlD);
                        else
                            ctrlD.actualizarRegistroD(mdlD);
                        this.dispose();
                    }
                    catch (Exception ex) 
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;    
                default:
                    break;
            }
            
        }
        else
            JOptionPane.showMessageDialog( null, "El producto debe tenre un codigo de barras", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
  }

    
    private void cmb(String CATEGORIA) throws ClassNotFoundException, SQLException
    {
        ModeloDetallesDispTabla mdlt;
        mdlt = new ModeloDetallesDispTabla("PRODUCTOS",CATEGORIA);
        if(CATEGORIA.equals("CATEGORIA"))
        {            
            txtCATEGORIA.removeAllItems();
            for(int i=0;i<mdlt.getRowCount();i++)
            {
                txtCATEGORIA.addItem((String) mdlt.getValueAt(i, 0));            
            }
        }
        if(CATEGORIA.equals("MARCA"))
        {
            cmbMARCA.removeAllItems();
            for(int i=0;i<mdlt.getRowCount();i++)
            {
                cmbMARCA.addItem((String) mdlt.getValueAt(i, 0));            
            }
        }
    }
    
    
