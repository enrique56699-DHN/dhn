    private void cmb(String campo, String atributo, JComboBox<String> comboDestino) throws ClassNotFoundException, SQLException {
    // 1. Determinar el JComboBox y la columna según el CAMPO
    //JComboBox<String> comboDestino;
    int columna;

    if ("LISTA".equals(campo)) {
        comboDestino = cmbDEPTO;
        columna = 1;
    } else {
        comboDestino = cmbPUESTO;
        columna = 2;
    }

    // 2. Limpiar el combo seleccionado
    comboDestino.removeAllItems();
    
    // 3. Cargar los datos del modelo
    ModeloEPuestosTabla mdl = new ModeloEPuestosTabla(0, campo, atributo);
    int totalFilas = mdl.getRowCount(); // Guardamos el total para no consultar el método en cada vuelta

    // 4. Bucle limpio y rápido
    for (int i = 0; i < totalFilas; i++) {
        comboDestino.addItem((String) mdl.getValueAt(i, columna));
    }
}
    
    
