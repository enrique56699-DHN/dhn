    private void actualizarTablas() throws ClassNotFoundException, SQLException
    {
        ModeloVacacionesTabla met;
        met = new ModeloVacacionesTabla();
        jtblVACACIONES.setModel(met);
        F.dimensionar(jtblVACACIONES,"VACACIONES");
    }
    
    private void seleccion() throws ClassNotFoundException, SQLException, Exception
    {
        int fila = jtblVACACIONES.getSelectedRow();
        IDVACACION = (int) jtblVACACIONES.getValueAt(fila, 0);
        empleado = jtblVACACIONES.getValueAt(fila, 1).toString();
        registro = jtblVACACIONES.getValueAt(fila, 2).toString();
        salida = jtblVACACIONES.getValueAt(fila, 3).toString();
        regreso = jtblVACACIONES.getValueAt(fila, 4).toString();
        diast = (int) jtblVACACIONES.getValueAt(fila, 5); 
        descripcion = jtblVACACIONES.getValueAt(fila, 6).toString();      
        PERIODOT = (int) jtblVACACIONES.getValueAt(fila, 7);    
        
        ModeloPrestaciones mdl;
        ControlPrestaciones ctrl = new ControlPrestaciones();
        mdl=ctrl.VacacionPeriodo("PRIMA VACACIONAL",+PERIODOT);
        PERIODO=PERIODOT + " - "+mdl.getFINI() + " - " + mdl.getFFIN();
    }
    
    private void imprimir() throws ClassNotFoundException, SQLException, IOException, Exception 
    {
        seleccion();
        ImpVACACIONES pca = new ImpVACACIONES(registro, salida, regreso, descripcion,empleado, ""+diast, PERIODO);
        JButton[] opciones = pca.getButtons();
        JOptionPane.showInternalOptionDialog(this, pca, "Imprimir VACACIONES",JOptionPane.OK_CANCEL_OPTION,-1, null, opciones, opciones[0]);
        if(pca.getOpcion() != null)
            pca.Imprimir();
    }

