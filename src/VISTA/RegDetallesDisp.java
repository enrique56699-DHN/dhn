    public void mostrar(int IDD, String ACCION, String TABLA, String CATEGORIA) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.TABLA = TABLA;
        this.CATEGORIA = CATEGORIA;

        switch(ACCION)
        {
            case "NUEVO":
                txtDESCRIPCION.requestFocus();
                break;
            case "EDITAR":
                ModeloDetallesDisp pto;
                ControlDetallesDisp ctrl = new ControlDetallesDisp();
                pto=ctrl.getRegistrosID(IDD);        
                this.txtDESCRIPCION.setText(pto.getDESCRIPCION());   
                break;
            default: break;
        }

    }
    
