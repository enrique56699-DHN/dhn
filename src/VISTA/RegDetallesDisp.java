    private void guardar(String ACCION) throws Exception
    {
        ModeloDetallesDisp mdl = new ModeloDetallesDisp();        
        //mdl.setIDDD(Integer.valueOf(IDDD);
        mdl.setTABLA(TABLA);
        mdl.setCATEGORIA(CATEGORIA);
        mdl.setDESCRIPCION(txtDESCRIPCION.getText());        
            
        
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            //IDANTENA = F.Registro("ANTENAS","IDANTENA","DESC");
                            //antenas.setIDANTENA(IDANTENA);

                            ControlDetallesDisp cp = new ControlDetallesDisp();
                            cp.guardarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {
                            ControlDetallesDisp cp = new ControlDetallesDisp();
                            cp.actualizarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default:
                        break;
                }
        
        
    } 
    
