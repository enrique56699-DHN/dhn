    public void mostrar(int IDANTENA, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDANTENA = IDANTENA;
        switch(ACCION)
        {
            case "NUEVO":
                this.txtNOMBRE.requestFocus();
                break;
            case "EDITAR":
                ModeloAntenas pto;
                ControlAntenas ca = new ControlAntenas();
                pto=ca.getRegistro(IDANTENA);
                
                this.txtID.setText(""+pto.getIDANTENA());
                this.txtMODELO.setSelectedItem(""+pto.getMODELO());
                this.txtNOMBRE.setText(""+pto.getNOMBRE());
                this.txtMARCA.setSelectedItem(pto.getMARCA());
                this.txtIP.setText(""+pto.getIP());
               
                this.txtIPPADRE.setText(pto.getIPPADRE());
                this.txtSITIO.setSelectedItem(pto.getSITIO());
                
                break;
            default:
                break;
        }
    }
   
    private void cmb() throws ClassNotFoundException, SQLException
    {
        txtMODELO.removeAllItems();
        txtMARCA.removeAllItems();
        txtSITIO.removeAllItems();
       
        //int NUM = mdlt.getRowCount();
        mdlt = new ModeloDetallesDispTabla(TABLA,"MODELO");
        for(int i=0;i<mdlt.getRowCount();i++)
        {
            txtMODELO.addItem((String) mdlt.getValueAt(i, 0));            
        }
        
        mdlt = new ModeloDetallesDispTabla(TABLA,"MARCA");
        for(int i=0;i<mdlt.getRowCount();i++)
        {
            txtMARCA.addItem((String) mdlt.getValueAt(i, 0));            
        }
        
        mdlt = new ModeloDetallesDispTabla(TABLA,"SITIO");
        for(int i=0;i<mdlt.getRowCount();i++)
        {
            txtSITIO.addItem((String) mdlt.getValueAt(i, 0));            
        }
    }
    
    private void guardar(String ACCION) throws Exception
    {
        ModeloAntenas antenas = new ModeloAntenas();

        antenas.setMODELO(txtMODELO.getSelectedItem().toString());
        antenas.setNOMBRE(txtNOMBRE.getText());
        antenas.setMARCA(txtMARCA.getSelectedItem().toString());        
        antenas.setIP(txtIP.getText());
        antenas.setSITIO(txtSITIO.getSelectedItem().toString());
        antenas.setIPPADRE(txtIPPADRE.getText());        
        
        switch(ACCION)
        {
            case "NUEVO":
                try
                {
                    IDANTENA = F.Registro("ANTENAS","IDANTENA","DESC");
                    antenas.setIDANTENA(IDANTENA);

                    ControlAntenas cp = new ControlAntenas();
                    cp.guardarRegistro(antenas);
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    antenas.setIDANTENA(Integer.valueOf(String.valueOf(txtID.getText())));

                    ControlAntenas cp = new ControlAntenas();
                    cp.actualizarRegistro(antenas);
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }
    } 
    
