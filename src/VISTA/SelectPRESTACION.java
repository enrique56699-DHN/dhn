    private void editar() throws SQLException, Exception
    {        
        seleccion();
        RegPrestaciones p = new RegPrestaciones(null,true);
        p.mostrar(IDPRESTACION,"EDITAR",CONCEPTO);
        p.setVisible(true);
        //refrescar(CONCEPTO);
    }
    
    private void dimensionar(JTable tabla)
    {
        tabla.getColumnModel().getColumn(0).setPreferredWidth(30);
        tabla.getColumnModel().getColumn(1).setPreferredWidth(30);
        //tabla.getTableHeader().setVisible(false);
        
        tabla.setAutoCreateRowSorter(true);
        
    }
    
    private void seleccion() throws ClassNotFoundException, SQLException
    {
        fila = tblPRESTACIONES.getSelectedRow();
        IDPRESTACION = (int) tblPRESTACIONES.getValueAt(fila, 0);
    }

    public void mostrar(String CONCEPTO) throws ClassNotFoundException, SQLException, Exception
    {  
        ModeloPrestacionesTabla mtpn;
        this.CONCEPTO = CONCEPTO;
        mtpn = new ModeloPrestacionesTabla(CONCEPTO);
        tblPRESTACIONES.setModel(mtpn);
        dimensionar(tblPRESTACIONES);
    }
    
    private void actualizarTablas(String CONCEPTO) throws ClassNotFoundException, SQLException
    {
        ModeloPrestacionesTabla mtpn;
        this.CONCEPTO = CONCEPTO;
        mtpn = new ModeloPrestacionesTabla(CONCEPTO);
        tblPRESTACIONES.setModel(mtpn);
        dimensionar(tblPRESTACIONES);
    }

    private void seleccionarPERIODO() throws ClassNotFoundException, SQLException, Exception
    {
        seleccion();
        ControlPrestaciones cp = new ControlPrestaciones();
        cp.actualizarSELECCION(0,"", CONCEPTO);
        ControlPrestaciones cp1 = new ControlPrestaciones();
        cp1.actualizarSELECCION(IDPRESTACION, "SELECCIONADO", CONCEPTO);
        this.dispose();                                  
    }            

    private void nuevoPERIODO() throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        RegPrestaciones dir = null;
        dir = new RegPrestaciones(null,true);
        int ultimo = F.Registro("PRESTACIONES","IDPRESTACION","DESC");
        dir.mostrar(ultimo,"NUEVO",CONCEPTO);
        dir.setVisible(true);            
        actualizarTablas(CONCEPTO);
    }
    

