    public static void funcion(int IDPENDIENTE) throws ClassNotFoundException, SQLException, Exception
    {        
        ModeloOrdenesP mdl;
        ControlOrdenesP ctrl = new ControlOrdenesP();
        mdl = ctrl.getRegistrosIDCONT(IDPENDIENTE);
        int IDORDENP = mdl.getIDORDENP();
        abrir(IDPENDIENTE,IDORDENP);
    }

