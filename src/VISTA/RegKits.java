    {
        RegKitsCategorias reg;
        reg = new RegKitsCategorias(null, true);
        //reg.mostrar(IDPENDIENTE, IDORDENP, ACCION);
        reg.setVisible(true);        
        llamarCategorias();              
        
    }
    
    private void llamarCategorias() throws ClassNotFoundException, SQLException
    {
        ModeloKitsCategoriasTabla mdl = new ModeloKitsCategoriasTabla();
        
        txtCATEGORIAS.removeAllItems();
        int NUM = mdl.getRowCount();
        if (NUM==0)
            {
                 txtCATEGORIAS.addItem("Ingresa categorias primero");
            }
        else
        {
            for(int i=0;i<NUM;i++)
            {
                //System.out.println("Este vale: "+mdl.getValueAt(i, 0));
                txtCATEGORIAS.addItem(""+ mdl.getValueAt(i, 0));
            } 
        }
    }
    
