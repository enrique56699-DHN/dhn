    private void guardar(String ACCION)
    {        
        if(this.txtNOMBRE.getText().equals(""))
        {
            JOptionPane.showMessageDialog( null, "CAMPO NO PUEDE ESTAR VACIO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
            this.txtNOMBRE.requestFocus();
        }
        else
        {                                        
            ModeloKits mod = new ModeloKits();

            mod.setIDKIT(IDKIT);
            mod.setNOMBRE(txtNOMBRE.getText().toUpperCase().trim());
            mod.setCOSTO(Float.parseFloat(txtCOSTO.getText()));
            mod.setPRECIO(Float.parseFloat(txtPRECIO.getText()));
            mod.setCATEGORIA(txtCATEGORIAS.getSelectedItem().toString());
            if(!lblARCHIVO2.getText().equals("Arrasta y Suelta"))
                mod.setFOTO(lblARCHIVO2.getText());
            else
                mod.setFOTO(null);
            
            switch(ACCION)
            {
                case "NUEVO":
                    try
                    {
                        IDKIT = F.Registro("KITS","IDKIT","DESC");
                        mod.setIDKIT(IDKIT);

                        ControlKits cp = new ControlKits();
                        cp.guardarRegistro(mod);
                        opciones(true);
                        this.btnGuardar.setEnabled(false);
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                    }
                    break;
                case "EDITAR":
                    try
                    {
                        ControlKits cp = new ControlKits();
                        cp.actualizarRegistro(mod);
                        this.dispose();
                    } 
                    catch (Exception ex) 
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                default:
                    break;

            }                
        }                
    }
    
