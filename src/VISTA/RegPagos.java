    public void mostrar(int IDNOTA, String ACCION, String F_CORTE) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        switch(ACCION)
        {
            case "NUEVO":
                this.dte_fecha.setDate(G.hoy());
                break;
            case "EDITAR":
                ModeloPagos mdl;
                ControlPagos ctrl = new ControlPagos();
                mdl = ctrl.getRegistrosID(IDNOTA);
                                
                this.IDNOTA = IDNOTA;        
                this.txtIDNOTA.setText(""+IDNOTA);
                this.lblCLIENTE.setText(""+mdl.getNOMBRE());
                this.F_CORTE = F_CORTE;
                IDCONTRATO = mdl.getIDCONTRATO();
                this.txtIDCONTRATO.setText(""+IDCONTRATO);
                this.dte_fecha.setDate(fecha=G.formato.parse(mdl.getFECHA()));
                this.txtMETODO.setSelectedItem(mdl.getMETODO());
                this.txtMONTO.setText(""+mdl.getMONTO());
                this.txtCOMENTARIOS.setText(mdl.getCOMENTARIOS());
                this.REFERENCIA=mdl.getREFERENCIA();
                //this.IDCAJA=mdl.getIDCAJA();
                this.lblARCHIVO.setText(mdl.getDOC());
                this.lblARCHIVO2.setText(mdl.getDOC());
                F.DragAndDrop(this.lblARCHIVO2,"VOUCHER",IDCONTRATO+"-"+txtMETODO.getSelectedItem().toString());
                pack();                
                break;
            default:
                break;
        }
           
    }
    
