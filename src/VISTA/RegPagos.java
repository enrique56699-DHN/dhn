    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            METODO = txtMETODO.getSelectedItem().toString();
            String DOC = null;
            String COMENTARIOS = txtCOMENTARIOS.getText();           
            switch(METODO)
            {
                case "OXXO":
                    if(!lblARCHIVO2.getText().equals("ARCHIVO"))
                        DOC = lblARCHIVO2.getText();
                    else
                        DOC = lblARCHIVO2.getText();
                    REFERENCIA = "NO VERIFICADO";
                    COMENTARIOS = "FECHA: " + G.formato.format(dteFDOC.getDate())
                           + " AUTORIZACION: " + txtREF.getText()
                           + "\n"+txtCOMENTARIOS.getText();
                    break;
                case "TRANSFERENCIA":
                    if(!lblARCHIVO2.getText().equals("ARCHIVO"))
                        DOC = lblARCHIVO2.getText();
                    else
                        DOC = lblARCHIVO2.getText();
                    REFERENCIA = "NO VERIFICADO";
                    COMENTARIOS = "FECHA: " + G.formato.format(dteFDOC.getDate())
                           //+ " AUTORIZACION: " + txtREF.getText()
                           + " ORIGEN: " + cmbORIGEN.getSelectedItem().toString()
                           + " DESTINO: " + cmbDESTINO.getSelectedItem().toString()
                           + "\n"+txtCOMENTARIOS.getText();                    
                    break;
                default: 
                    break;
                    
            }
            txtCOMENTARIOS.setText("");
            txtCOMENTARIOS.setText(COMENTARIOS);

            float MONTO = Float.parseFloat(txtMONTO.getText());
            if(REFERENCIA.equals("RECHAZADO"))            
                REFERENCIA = "NO VERIFICADO";
            
            ControlPagos cp = new ControlPagos();
            cp.actualizarPagos(IDNOTA, METODO, COMENTARIOS, MONTO,REFERENCIA,DOC);
            
            JOptionPane.showMessageDialog( null, "REGISTRO ACTUALIZADO CORRECTAMENTE", "ACTUALIZANDO", JOptionPane.INFORMATION_MESSAGE);        
            this.dispose();
            
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(RegPagos.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(RegPagos.class.getName()).log(Level.SEVERE, null, ex);
        } catch (Exception ex) {
            Logger.getLogger(RegPagos.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

