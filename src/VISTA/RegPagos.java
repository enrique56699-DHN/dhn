    private void cancelarPago() throws ClassNotFoundException, SQLException, Exception 
    {
        // 1. Reutilización de instancias y obtención de datos del contrato
        ControlContratos ctrl = new ControlContratos();
        int costo = ctrl.costo(IDCONTRATO);       
        ModeloContratos mdl = ctrl.getRegistrosID(IDCONTRATO);
        String ipc = mdl.getIP();

        // 2. Cancelación del pago
        ControlPagos cp = new ControlPagos();
        cp.cancelarPago(IDNOTA, 0, "CANCELADO!...#Contrato: " + IDCONTRATO, "CANCELADO");

        // Variable local para la fecha de corte (evita usar variables globales/de clase para esto)
        String fechaCorteActualizada = F_CORTE; 

        // 3. Recalcular fecha de corte si el pago no estaba verificado ni rechazado
        if (!"VERIFICADO".equals(REFERENCIA) && !"RECHAZADO".equals(REFERENCIA)&& !"AUTORIZADO".equals(REFERENCIA)) {
            float montoLocal = Float.parseFloat(txtMONTO.getText());
            int mesesARestar = (int) (montoLocal / costo);

            Date nCorte = G.formato.parse(F_CORTE);

            Calendar calendar = Calendar.getInstance();
            calendar.setTime(nCorte);
            calendar.add(Calendar.MONTH, -mesesARestar);

            fechaCorteActualizada = G.formato.format(calendar.getTime()); 

            ctrl.actualizarCorte(fechaCorteActualizada, IDCONTRATO);
        }

        // 4. Automatización del servicio
        F.automatizacion("VERIFICA", ipc, IDCONTRATO, fechaCorteActualizada);        
    }
    
    private void pregunta() throws SQLException, Exception
    {
        Object[] inputFields = {"¿DESEAS ELIMINAR EL PAGO DEL CLIENTE?\n"};

        int option = JOptionPane.showConfirmDialog(this, inputFields, "Eliminar pago", JOptionPane.OK_CANCEL_OPTION, JOptionPane.INFORMATION_MESSAGE);
        if (option == JOptionPane.OK_OPTION)        
            cancelarPago();        
    }
    
