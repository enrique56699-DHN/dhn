    public void mostrar(int IDVEHICULO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDVEHICULO = IDVEHICULO;
        switch(ACCION)
        {
            case "NUEVO":
                this.txtMARCA.requestFocus();
                break;
            case "EDITAR":
                ModeloVehiculos mdl;
                ControlVehiculos ctrl = new ControlVehiculos();
                mdl=ctrl.getRegistros(IDVEHICULO);
                
                this.txtIDVEHICULO.setText(""+mdl.getIDVEHICULO());
                this.txtMARCA.setText(""+mdl.getMARCA());
                this.txtMODELO.setText(""+mdl.getMODELO());
                this.txtNMOTOR.setText(""+mdl.getNMOTOR());
                this.txtEMPRESA.setSelectedItem(""+mdl.getEMPRESA());
                this.txtNS.setText(""+mdl.getNS());
                this.txtPLACA.setText(""+mdl.getPLACA());
                
                break;
            default: break;
        }
    }
   
    private void guardar(String ACCION) throws Exception
    {
        ModeloVehiculos mdl = new ModeloVehiculos();

        //mdl.setIDVEHICULO(Integer.parseInt(String.valueOf(txtIDVEHICULO.getText())));
        mdl.setMARCA(txtMARCA.getText());
        mdl.setMODELO(txtMODELO.getText());
        mdl.setNS(txtNS.getText());
        mdl.setNMOTOR(txtNMOTOR.getText());        
        mdl.setPLACA(txtPLACA.getText());
        
        mdl.setEMPRESA(txtEMPRESA.getSelectedItem().toString());
       
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            //IDVEHICULO = F.Registro("VEHICULOS","IDVEHICULO","DESC");
                            //mdl.setIDVEHICULO(IDVEHICULO);
                            ControlVehiculos ctrl = new ControlVehiculos();
                            ctrl.guardarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {                            
                            mdl.setIDVEHICULO(Integer.parseInt(String.valueOf(txtIDVEHICULO.getText())));
                            
                            ControlVehiculos ctrl = new ControlVehiculos();
                            ctrl.actualizarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default:
                        break;
                }       
        
    } 
    
