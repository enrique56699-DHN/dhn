    public void mostrar(int IDPAQUETE, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDPAQUETE = IDPAQUETE;
        switch(ACCION)
        {
            case "NUEVO":
                this.txtDESCRIPCION.requestFocus();
                break;
            case "EDITAR":
                ModeloPaquetes pto;
                ControlPaquetes cp = new ControlPaquetes();
                pto=cp.getRegistrosID(IDPAQUETE);
                
                this.txtID.setText(""+pto.getIDPAQUETE());
                this.txtCOSTO.setText(""+pto.getCOSTO());
                this.txtDESCRIPCION.setText(""+pto.getDESCRIPCION());
                break;
            default: break;
        }    
       
    }
    
    private void guardar(String ACCION)
    {                                          
        ModeloPaquetes md = new ModeloPaquetes();

        md.setIDPAQUETE(IDPAQUETE);
        md.setCOSTO(Integer.parseInt(txtCOSTO.getText().trim()));
        md.setDESCRIPCION(txtDESCRIPCION.getText());

        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDPAQUETE = F.Registro("PAQUETES", "IDPAQUETE", "DESC");
                    md.setIDPAQUETE(IDPAQUETE);
                    
                    ControlPaquetes cp = new ControlPaquetes();
                    cp.guardarRegistro(md);
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    ControlPaquetes cp = new ControlPaquetes();
                    cp.actualizarRegistro(md);
                    this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default: break;

        }          
         
    }

