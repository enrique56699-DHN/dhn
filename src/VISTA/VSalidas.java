    private void seleccion() throws ClassNotFoundException, SQLException, Exception
    {
        if(tblTABLA.getRowCount() > 0)
        {
            int fila = tblTABLA.getSelectedRow();
            IDSALIDA = (int) tblTABLA.getValueAt(fila, 0);
            descripcion = tblTABLA.getValueAt(fila, 1).toString();
            monto =  tblTABLA.getValueAt(fila, 2).toString();
            categoria = tblTABLA.getValueAt(fila, 3).toString();
            DE = tblTABLA.getValueAt(fila, 4).toString();
        }        
    }
    
    private void actualizarTablas() throws ClassNotFoundException, SQLException
    {
        ModeloSalidasTabla mst;
        mst = new ModeloSalidasTabla();
        tblTABLA.setModel(mst);
        F.dimensionar(tblTABLA,"SALIDAS");
    }
    
    private void accion(String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        try
        {
            if(ACCION.equals("BORRAR"))
            {
                seleccion();
                int eleccion = JOptionPane.showConfirmDialog(null, "Realmente Desea Eliminar el registro?");
                if ( eleccion == 0)
                {
                    try
                    {
                        try
                        {                            
                            F.eliminarRegistro(IDSALIDA, "SALIDAS", "IDSALIDA");
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ELIMINAR LOS DATOS DE LA TABLA", "ERROR", JOptionPane.ERROR_MESSAGE);
                        }
                    }
                    catch (HeadlessException ex)
                    {
                        JOptionPane.showMessageDialog( null, "PARA PODER ELIMINAR UN REGISTRO,\nPRIMERO DEBE SELECCIONAR UNA FILA DE LA TABLA", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
                    }
                }
            }
            else
            {
                try
                {
                    if(ACCION.equals("NUEVO"))                    
                        IDSALIDA = 0;
                    
                    RegSalidas p = new RegSalidas(null,true);
                    p.mostrar(IDSALIDA,ACCION,"");
                    p.setVisible(true);

                }
                catch (ParseException ex)
                {
                    JOptionPane.showMessageDialog( null, "PARA PODER EDITAR UN REGISTRO,\nPRIMERO DEBE SELECCIONAR UNA FILA DE LA TABLA", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
                }
                actualizarTablas();
            }
        }
        catch (ParseException ex)
        {
            JOptionPane.showMessageDialog( null, "PARA PODER EDITAR UN REGISTRO,\nPRIMERO DEBE SELECCIONAR UNA FILA DE LA TABLA", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
        }        
        
    }
    
    private void imprimir() throws IOException, ClassNotFoundException, SQLException, Exception
    {
        seleccion();
        ImpSALIDA pca = new ImpSALIDA(DE,""+IDSALIDA,monto,descripcion,categoria);
        JButton[] opciones = pca.getButtons();
        JOptionPane.showInternalOptionDialog(this, pca, "Imprimir SALIDAS",JOptionPane.OK_CANCEL_OPTION,-1, null, opciones, opciones[0]);
        if(pca.getOpcion() != null)
            pca.Imprimir();
    }

