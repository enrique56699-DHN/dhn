    private String MOTIVOS()
    {
        String MOTIVOS = "";
        Component[] componentes = pnlMOTIVOS.getComponents();
        for (Component c : componentes) {
            if (c instanceof JCheckBox) {
                JCheckBox cb = (JCheckBox) c;
                // Comprobar si está seleccionado
                if (cb.isSelected()) {
                    MOTIVOS = MOTIVOS + cb.getText().toUpperCase()+" - ";
                }
            }
        }        
        return MOTIVOS;
    }

    private void guardar(String ACCION) throws ClassNotFoundException, SQLException, Exception
    { 
        if(!MOTIVOS().equals(""))
        {
            F.bitacora("PENDIENTES",IDSERVICIO,ACCION,G.IDUSER,MOTIVOS(),"");
            reagendar(FEST);
        }            
        else
            JOptionPane.showMessageDialog( null, "NO PUEDES REAGENDAR EL SERVICIO SIN UN MOTIVO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
    }
    
    private void reagendar(String FEST) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        if(!chkM10.isSelected())   
        {
            if(FEST.equals(""))        
            FEST=G.FECHA(G.hoy(),false);
       
            Date DFEST = G.formato.parse(FEST);             

            String dayOfWeek;
            String dia;

            Calendar calendar = Calendar.getInstance();
            calendar.setTime(DFEST);
            //calendar.add(Calendar.DAY_OF_WEEK,i);
            dayOfWeek = calendar.getDisplayName(Calendar.DAY_OF_WEEK, Calendar.LONG, Locale.US).toUpperCase();
            //dia = nomdias(dayOfWeek);

            switch(dayOfWeek)
            {
                case "MONDAY":
                    dia = "LUNES";
                    calendar.add(Calendar.DAY_OF_WEEK,1);
                    break;
                case "TUESDAY":
                    dia = "MARTES";
                    calendar.add(Calendar.DAY_OF_WEEK,1);
                    break;
                case "WEDNESDAY":
                    dia = "MIERCOLES";
                    calendar.add(Calendar.DAY_OF_WEEK,1);
                    break;
                case "THURSDAY":
                    dia = "JUEVES";
                    calendar.add(Calendar.DAY_OF_WEEK,1);
                    break;
                case "FRIDAY":
                    dia = "VIERNES";
                    calendar.add(Calendar.DAY_OF_WEEK,3);
                    break;
                case "SATURDAY":
                    dia = "SABADO";
                    calendar.add(Calendar.DAY_OF_WEEK,2);
                    break;
                case "SUNDAY":
                    dia = "DOMINGO";
                    calendar.add(Calendar.DAY_OF_WEEK,1);
                    break;
                default: break;
            }

            DFEST=calendar.getTime();
            FEST=""+G.formato.format(DFEST);
        }
        else
           FEST=""+G.formato.format(dteFEST.getDate());         
        
        ControlPendientes ctrlP = new ControlPendientes();        
        ctrlP.actualizarFEST(FEST, IDSERVICIO);
    }
    
    

