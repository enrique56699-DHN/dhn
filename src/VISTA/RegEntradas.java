    public void mostrar(int IDENTRADA, String ACCION, String DESCRIPCION) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        switch(ACCION)
        {
            case "NUEVO":
                ///this.dte_fecha.setDate(G.hoy());
                
                this.txtDESCRIPCION.requestFocus();
                break;
            case "EDITAR":
                ModeloEntradas pto;
                ControlEntradas ce = new ControlEntradas();
                pto=ce.getRegistrosID(IDENTRADA);
                
                identradas = pto.getIDENTRADA();
                this.txtIDENTRADA.setText(""+pto.getIDENTRADA());
                this.txtDESCRIPCION.setText(""+pto.getDESCRIPCION());
                this.txtMONTO.setText(""+pto.getMONTO());
                this.dte_fecha.setDate(G.formato.parse(pto.getFECHA()));
                //this.dte_fecha.setDate(G.FECHA(pto.getFECHA()));
                //this.FECHA = pto.getFECHA();
                this.IDCAJA = pto.getIDCAJA();
                break;
            case "MAGISTV":
                //this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(DESCRIPCION);
                this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("MAGISTV");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("200");
                this.ACCION = "NUEVO";
                break;
            case "REUBICACION":
                //this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(DESCRIPCION);
                this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("GENERAL");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("400");
                this.ACCION = "NUEVO";
                break;
            case "MANTENIMIENTO":
                //this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(DESCRIPCION);
                this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("GENERAL");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("500");
                this.ACCION = "NUEVO";
                break;                
            case "CONCILIACION":
                this.AUX = ACCION;
                this.dte_fecha.setDate(G.hoy());
                this.dte_fecha.setEnabled(true);
                this.REF = DESCRIPCION;
                this.FAC = txtFAC.getText();
                this.ACCION = "NUEVO";
                this.txtFAC.setVisible(true);
                this.chkFAC.setVisible(true);
                break;
            default: break;
        }        
    }
    
    private void guardar(String ACCION)
    {
        if(this.txtDESCRIPCION.getText().equals(""))
         {
             JOptionPane.showMessageDialog( null, "CAMPO NO PUEDE ESTAR VACIO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
             this.txtDESCRIPCION.requestFocus();
         }
            else
            {
                ModeloEntradas md = new ModeloEntradas();
                descripcion=txtDESCRIPCION.getText();
                monto=Float.parseFloat(txtMONTO.getText());
                categoria=txtCATEGORIA.getSelectedItem().toString();
                METODO=txtMETODO.getSelectedItem().toString();
                md.setIDENTRADA(identradas);
                md.setDESCRIPCION(descripcion);
                md.setMONTO(monto);
                md.setCATEGORIA(categoria);
                md.setMETODO(METODO);
                md.setFECHA(G.FECHA(dte_fecha.getDate(), true));
                //md.setFECHA(FECHA);
                md.setIDCAJA(IDCAJA);
                
                switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            identradas = F.Registro("ENTRADAS","IDENTRADA","DESC");
                            md.setIDENTRADA(identradas);

                            ControlEntradas cp = new ControlEntradas();
                            cp.guardarRegistro(md);
                            
                            switch(AUX)
                            {
                                /*case "CONDONACON":
                                    ModeloPagos mdlP;
                                    ControlPagos ctrlP = new ControlPagos();

                                    mdlP = ctrlP.getRegistrosIDR(IDNOTA);
                                    String COMENTARIOS = mdlP.getCOMENTARIOS()+"-"+"PAGO CONDONADO SALIDA "+idsalidas;

                                    ControlPagos ctrlP1;
                                    ctrlP1 = new ControlPagos();
                                    ctrlP1.actualizarComentarios(COMENTARIOS, IDNOTA);  
                                    break;*/
                                
                                case "CONCILIACION":
                                    ModeloMovD mdl = new ModeloMovD();        

                                    /*int IDMOVD = F.Registro("MOVD","IDMOVD","DESC");
                                    mdl.setIDMOVD(IDMOVD);*/

                                    mdl.setIDMOVIMIENTO(identradas);
                                    mdl.setMOVIMIENTO("ENTRADAS");
                                    mdl.setREF(REF);
                                    mdl.setCOTEJADO(false);
                                    mdl.setFAC(txtFAC.getText());
                                    
                                    ControlMovD ctrlMD = new ControlMovD();
                                    ctrlMD.guardarRegistro(mdl);
                                    break;
                                default:
                                    break;
                            }
                            
                            APOYO();
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO ", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                            System.out.println(ex);
                        }
                        break;
                    case "EDITAR":
                        try
                        {
                            ControlEntradas cp = new ControlEntradas();
                            cp.actualizarRegistro(md);
                            APOYO();
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default: break;
                }
                
            }
        
    }
    
    private void APOYO() throws SQLException, Exception
    {
        JInternalFrame ji = validador.getJInternalFrame(VApoyo.class.getName());
        if(ji != null )
            ji.dispose();
        ji = new VApoyo("ENTRADA",G.formato.format(dte_fecha.getDate()),""+identradas,""+G.numero.format(monto)+".00",descripcion,categoria);
        Principal.getCONT().add(ji);
        validador.addJIframe(VApoyo.class.getName(), ji);
        RegEntradas.btnCERRAR.doClick();
        this.dispose();

        ji.setMaximum(true);        
    }
    
