    public void mostrar(int IDCONTRATO, int IDCLIENTE, String ACCION) throws ParseException, Exception
    {
        this.ACCION = ACCION;
        this.IDCONTRATO = IDCONTRATO;
        this.IDCLIENTE = IDCLIENTE;
        cliente(IDCLIENTE);
        
        switch(ACCION)
        {
            case "NUEVO":
                direcciones(IDCLIENTE,0);
                paquetes(0);
                break;
            case "EDITAR":
                dte_Instalacion.setEnabled(true);
                dte_Corte.setEnabled(true);
                ModeloContratos pto;
                ControlContratos cc = new ControlContratos();
                pto=cc.getRegistrosID(IDCONTRATO);
                this.txtNCONTRATO.setText(""+pto.getIDCONTRATO());
                this.dte_fecha.setDate(G.formato.parse(pto.getFREG()));

                this.IDCLIENTE=pto.getIDCLIENTE();
                cliente(IDCLIENTE);
                this.IDDIRECCION=pto.getIDDIRECCION();
                direcciones(IDCLIENTE,IDDIRECCION);
                IDPAQUETE=pto.getIDPAQUETE();
                paquetes(IDPAQUETE);
                this.dte_Instalacion.setDate(G.formato.parse(pto.getFINS())); 
                this.dte_Corte.setDate(G.formato.parse(pto.getFCOR()));
                this.txtCOMENTARIOS.setText(""+pto.getCOMENTARIOS());
                DESCRIPCION=""+pto.getCOMENTARIOS();
                this.lblEQUIPO.setText(pto.getEQUIPO());

                this.lblIP.setText(pto.getIP());
                this.NCORTE=pto.getFCOR();
                
                this.ESTADO=pto.getESTADO();
                this.txtESTADO.setSelectedItem(ESTADO);
               
                this.chkCONT.setSelected(pto.getCONT());
                Etiqueta();
                
                break;
            default: break;
        }        
    }
        
    private void guardar(String ACCION) throws SQLException, Exception
    {                                  
        ModeloContratos x = new ModeloContratos();

        x.setIDCONTRATO(IDCONTRATO);
        x.setIDCLIENTE(IDCLIENTE);
        x.setIDDIRECCION(IDDIRECCION(IDCLIENTE));

        x.setIDPAQUETE(IDPAQUETE());
        x.setFREG(""+G.formato.format(dte_fecha.getDate()));
        x.setFINS(""+G.formato.format(dte_Instalacion.getDate()));
        x.setCOMENTARIOS(txtCOMENTARIOS.getText());
        x.setESTADO(txtESTADO.getSelectedItem().toString());
        x.setFCOR(""+G.formato.format(dte_Corte.getDate()));
        x.setEQUIPO(lblEQUIPO.getText());
        x.setIP(lblIP.getText());
        x.setCONT(this.chkCONT.isSelected());

        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDCONTRATO = F.Registro("CONTRATOS","IDCONTRATO","DESC");
                    x.setIDCONTRATO(IDCONTRATO);
                    ESTADO = "PENDIENTE";
                    x.setESTADO(ESTADO);

                    ControlContratos cp = new ControlContratos();
                    cp.guardarRegistro(x);                    
                    
                    String[] datos = {""+IDCONTRATO, ""+G.formato.format(dte_fecha.getDate()), txtNOMBRE.getText(), CALLE, NUMERO, TELEFONO, COLONIA, LOCALIDAD, IDENTIFICACION, REFERENCIA, LATITUD, LONGITUD,DESCRIPCIONp,""+COSTO};
                    rutaPDF = "\\"+"\\" +G.ip +"\\dhn\\CONTRATOS\\CONTRATOS-"+IDCONTRATO+".pdf";
                    F.imprimir(titulos,datos, rutaExcel, rutaWord, rutaWordtmp, rutaPDF);
                    
                    ModeloPendientes mdlP = new ModeloPendientes();
                    mdlP.setIDCLIENTE(IDCLIENTE);
                    mdlP.setIDDIRECCION(IDDIRECCION(IDCLIENTE));
                    mdlP.setNPEDIDO("DHN-3-"+IDCONTRATO);
                    mdlP.setNPEDIDOF("");
                    mdlP.setCATEGORIA("INTERNET");        
                    mdlP.setSUBCATEGORIA("GENERAL");      
                    mdlP.setDESCRIPCION("CONTRATO N: "+IDCONTRATO+"\n"+"INSTALACION DE SERVICIO DE INTERNET");     
                    mdlP.setCOMENTARIOS(txtCOMENTARIOS.getText());   
                    mdlP.setFREG(""+G.formato.format(dte_fecha.getDate()));
                    mdlP.setFEST(""+G.formato.format(dte_fecha.getDate()));
                    mdlP.setFFIN("");
                    int IDPENDIENTE = F.Registro("PENDIENTES","IDPENDIENTE","DESC");
                    mdlP.setIDPENDIENTE(IDPENDIENTE);
                    mdlP.setESTADO("ABIERTO");    
                    
                    ControlPendientes ctrl = new ControlPendientes();
                    ctrl.guardarRegistro(mdlP);
                    F.llenaCarrito("INSTALACION INTERNET", "INTERNET", IDPENDIENTE, 0);
                    F.bitacora("PENDIENTES",IDPENDIENTE,ACCION,G.IDUSER,"CONTRATO N: "+IDCONTRATO+"\n"+"INSTALACION DE SERVICIO DE INTERNET","");
                    
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    F.bitacora("CONTRATOS",IDCONTRATO,ACCION,G.IDUSER,""+txtCOMENTARIOS.getText(),DESCRIPCION);
                    ControlContratos cp = new ControlContratos();
                    cp.actualizarRegistro(x);                   
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }
        
        btnImprimir.setEnabled(true);
        btnGUARDAR.setEnabled(false);
    }
    
