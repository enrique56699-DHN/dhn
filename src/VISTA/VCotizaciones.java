    private void actualizarTablas(String ESTADO) throws ClassNotFoundException, SQLException, Exception
    {
        ModeloCotizacionesTabla mtc;
        mtc = new ModeloCotizacionesTabla("GLOBAL",0,ESTADO);
        tblTABLA.setModel(mtc);        
        mtc.fireTableDataChanged();
        F.dimensionar(tblTABLA,"COTIZACIONES");
    }
    
    private void seleccion() throws ClassNotFoundException, SQLException
    {
        int fila = tblTABLA.getSelectedRow();
        IDCOTIZACION = (int) tblTABLA.getValueAt(fila, 0);     
        IDPENDIENTE = (int) tblTABLA.getValueAt(fila, 1);     
        NARCHIVO = tblTABLA.getValueAt(fila, 8).toString();     
    }
    
    private void descargar() throws IOException
    {
        File ORIGEN = new File(rutaPDF+NARCHIVO);
        File DESTINO = new File (rutaDESTINO+NARCHIVO);
        FileUtils.copyFile(ORIGEN, DESTINO); 
        F.abrirArchivo(rutaDESTINO);
    }
    
