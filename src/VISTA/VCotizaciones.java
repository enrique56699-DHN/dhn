    private void tblTABLAKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tblTABLAKeyPressed
        if(F.ENTER(evt))
            try {
                seleccion();
                F.abrirArchivo(rutaPDF+NARCHIVO);
        } catch (ClassNotFoundException | SQLException ex) {
            Logger.getLogger(RegArticuloCarrito.class.getName()).log(Level.SEVERE, null, ex);
        }
        else
            if(F.SHIFT(evt))
            {
                try {
                    seleccion();
                    Rectangle rect = tblTABLA.getCellRect(tblTABLA.getSelectedRow(), 0, true);
                    jmpACCIONES.show(tblTABLA, rect.x, rect.y + rect.height);
                } catch (ClassNotFoundException ex) {
                    Logger.getLogger(VCotizaciones.class.getName()).log(Level.SEVERE, null, ex);
                } catch (SQLException ex) {
                    Logger.getLogger(VCotizaciones.class.getName()).log(Level.SEVERE, null, ex);
                } catch (Exception ex) {
                    Logger.getLogger(VCotizaciones.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
    }//GEN-LAST:event_tblTABLAKeyPressed

