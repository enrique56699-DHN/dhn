    public void mostrar(int IDDIRECCION, int IDCLIENTE, String NOMBRE, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {        
        this.IDDIRECCION = IDDIRECCION;
        this.IDCLIENTE = IDCLIENTE;
        this.NOMBRE = NOMBRE;
        this.ACCION = ACCION;
        
        switch(ACCION)
        {
            case "NUEVO":
                this.txtCALLE.requestFocus();
                this.lblCLIENTE.setText(this.NOMBRE);
                break;
                
            case "EDITAR":
                ModeloDirecciones pto;
                ControlDirecciones cdir = new ControlDirecciones();
                pto = cdir.getRegistrosIDa(IDDIRECCION);
                
                this.txtID.setText(""+pto.getIDDIRECCION());
                this.lblCLIENTE.setText(this.NOMBRE);
                this.txtColonia.setText(""+pto.getCOLONIA());
                this.txtNumero.setText(""+pto.getNUMERO());
                this.txtLocalidad.setText(""+pto.getLOCALIDAD());
                this.txtLatitud.setText(""+pto.getLATITUD());
                this.lblVSATELITAL.setText(""+pto.getLONGITUD());
                this.lblVSTREET.setText(""+pto.getREFERENCIA());
                this.txtCALLE.setText(""+pto.getCALLE());
                
                break;
                
                default: break;
        }
       
    }
    
    private void guardar(String ACCION)
    {               
        ModeloDirecciones md = new ModeloDirecciones();

        md.setIDDIRECCION(IDDIRECCION);
        md.setIDCLIENTE(IDCLIENTE);
        md.setCALLE(txtCALLE.getText().trim());
        md.setNUMERO(txtNumero.getText());
        md.setCOLONIA(txtColonia.getText());
        md.setLOCALIDAD(txtLocalidad.getText());
        md.setLATITUD(txtLatitud.getText());
        md.setLONGITUD(lblVSATELITAL.getText());
        md.setREFERENCIA(lblVSTREET.getText());

        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDDIRECCION = F.Registro("DIRECCIONES","IDDIRECCION","DESC");
                    md.setIDDIRECCION(IDDIRECCION);

                    ControlDirecciones cp = new ControlDirecciones();
                    cp.guardarRegistro(md);
                    this.dispose();
                }
                catch (Exception ex)
                {
                   JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    ControlDirecciones cp = new ControlDirecciones();
                    cp.actualizarRegistro(md);
                    this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default: break;
        }       
    }    
    
