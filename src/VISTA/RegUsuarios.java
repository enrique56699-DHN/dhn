    public void mostrar(int IDUSUARIO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
       
        this.ACCION = ACCION;
        this.IDUSUARIO = IDUSUARIO;
        
        switch(ACCION)
        {
            case "NUEVO":
                this.txtNOMBRE.requestFocus();
                break;
                
            case "EDITAR":
                ModeloUsuarios mdl;
                ControlUsuarios ctrl = new ControlUsuarios();
                mdl=ctrl.getRegistros(IDUSUARIO,"");
                
                this.txtIDUSUARIO.setText(""+this.IDUSUARIO);
                this.txtNOMBRE.setText(""+mdl.getNOMBRE());
                this.pssPASS.setText(""+mdl.getPASSWORD());
                
                break;
                
                default: break;
        }
    }
    
    private void guardar(String ACCION)
    {            
        PASSWORD = String.copyValueOf(pssPASS.getPassword());
        String CPASSWORD = String.copyValueOf(pssPASSC.getPassword());
        if(PASSWORD.equals(CPASSWORD))
        {
            ModeloUsuarios mdl = new ModeloUsuarios();
            
            mdl.setNOMBRE(txtNOMBRE.getText());
            mdl.setPASSWORD(PASSWORD);
            mdl.setPRIVILEGIOS(txtPRIVILEGIOS.getSelectedItem().toString());

            switch(ACCION)
            {
                case "NUEVO":
                    try
                    { 
                        IDUSUARIO = F.Registro("USUARIOS","IDUSUARIO","DESC");
                        mdl.setIDUSUARIO(IDUSUARIO);

                        ControlUsuarios cp = new ControlUsuarios();
                        cp.guardarRegistro(mdl);
                        this.dispose();
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                    }
                    break;
                case "EDITAR":
                    try
                    {
                        ControlUsuarios cp = new ControlUsuarios();
                        cp.actualizarRegistro(mdl);
                        this.dispose();
                    } 
                    catch (Exception ex) 
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                default: break;

            }
        }
        else
            JOptionPane.showMessageDialog( null, "LAS CONTRASEÑAS NO COINCIDEN", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
         
    }
    

