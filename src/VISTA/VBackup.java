    private void seleccionar()
    {
        SimpleDateFormat dateformat=new SimpleDateFormat("ddMMyyyy");
        Date calendario=new Date();
        String mysqlDumpPath = "\\\\"+G.ip+"\\xampp\\mysql\\bin\\mysqldump.exe"; // Ruta de mysqldump
        String backupFilePath = G.rutaServidor+"RESPALDOS DB\\dhn" + dateformat.format(calendario.getTime()) + ".sql"; // Ruta de salida
        
        try
        {
            ProcessBuilder pb = new ProcessBuilder
            (
            mysqlDumpPath,
            "-h", G.ip,
            "-P", G.puerto,
            "-u", G.loginDB,
            "-p" + G.passwordDB,
            "--add-drop-database",
            "--databases", G.db
                );

            Process process = pb.start();
            InputStream is = process.getInputStream();
            FileOutputStream fos = new FileOutputStream(new File(backupFilePath));
            byte[] buffer = new byte[1024];
            int bytesRead;
            while ((bytesRead = is.read(buffer)) > 0) {
                fos.write(buffer, 0, bytesRead);
            }

            JOptionPane.showMessageDialog(null, "GENERADO CORRECTAMENTE", "EXITO",JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        }
        catch(IOException e)
        {
            JOptionPane.showMessageDialog(null, "ERROR, NO SE GENERO EL ARCHIVO DE RESPALDO\nPOR EL SIGUIENTE MOTIVO: " + e.getMessage(), "VERIFICAR",JOptionPane.ERROR_MESSAGE);
        }
            
    }
