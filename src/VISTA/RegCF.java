    public void mostrar(int IDVALE, String ACCION, String TIPO) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.TIPO=TIPO;
        switch(ACCION)
        {
            case "NUEVO":
                this.txtMONTO.requestFocus();
                break;
            case "EDITAR":
                ModeloCF mdl;
                ControlCF ctrl = new ControlCF();
                mdl=ctrl.getRegistrosID(IDCF);                
                this.txtIDVALE.setText(""+mdl.getIDCF());
                this.txtMONTO.setText(""+mdl.getMONTO());
                this.dteFECHA.setDate(G.formato.parse(mdl.getFECHA()));
                break;
            default:
                break;
        }        
    }
    
    private void guardar(String ACCION)
    {        
        ModeloCF mdl = new ModeloCF();

        mdl.setFECHA(G.FECHA(dteFECHA.getDate(),true));
        mdl.setTIPO(TIPO);
        mdl.setMONTO(Float.parseFloat(txtMONTO.getText()));
        switch(ACCION)
        {
            case "NUEVO":
                try
                {
                    IDCF = F.Registro("CF","IDCF","DESC");
                    mdl.setIDCF(IDCF);
                    ControlCF cp = new ControlCF();
                    cp.guardarRegistro(mdl);                            
                    APOYO();
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO ", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    System.out.println(ex);
                }
                break;
            case "EDITAR":
                try
                {
                    mdl.setIDCF(Integer.parseInt(txtIDVALE.getText()));

                    ControlCF cp = new ControlCF();
                    cp.actualizarRegistro(mdl);
                    APOYO();
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }               
    }
    
    private void APOYO() throws SQLException, Exception
    {
        JInternalFrame ji = validador.getJInternalFrame(VApoyo.class.getName());
        if(ji != null )
            ji.dispose();
        ji = new VApoyo("CF",G.formato.format(dteFECHA.getDate()),""+IDCF,""+G.numero.format(Float.parseFloat(txtMONTO.getText()))+".00","",TIPO);
        Principal.getCONT().add(ji);
        validador.addJIframe(VApoyo.class.getName(), ji);
        RegCF.btnCERRAR.doClick();
        this.dispose();
               
        ji.setMaximum(true);        
    }
    
