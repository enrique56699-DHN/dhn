    private void evento()
    {
        String texto="";
        try
        {
           br = new BufferedReader(new FileReader(fichero));
           //Leer la primera línea, guardando en un String
           texto = br.readLine();
           //Repetir mientras no se llegue al final del fichero
           while(texto != null)
           {               

               //Hacer lo que sea con la línea leída
               txtVERSION.append(texto);
               txtVERSION.append(System.getProperty("line.separator")); // Esto para el salto de línea
               //datos.add(texto+"\n");
               //Leer la siguiente línea
               texto = br.readLine();
           }
        }
        // Captura de excepción por fichero no encontrado
        catch (FileNotFoundException ex) {
            System.out.println("Error: Fichero no encontrado "+ex);
        }
        // Captura de cualquier otra excepción
        catch(IOException ex) {
            System.out.println("Error de lectura del fichero "+ex);
        }
        // Asegurar el cierre del fichero en cualquier caso
        finally {
            try {
                // Cerrar el fichero si se ha podido abrir
                if(br != null) {
                    br.close();
                }
            }
            catch (IOException ex) {
                System.out.println("Error al cerrar el fichero "+ex);
            }
        }
    }

