    public void mostrar(String CONSULTA, int ID, String ACCION,int IDEMPLEADO) throws ClassNotFoundException, SQLException, Exception
    {        
        this.ACCION = ACCION;
        switch(CONSULTA)
        {
            case "IDPDOC":
                IDPDOC = ID;
                break;
            case "IDPENDIENTE":
                IDPENDIENTE=ID;
                break;
            default:
                break;
        }
        
        switch(ACCION)
        {
            case "NUEVO":
                this.txtIDPENDIENTE.setText(""+IDPENDIENTE);
                this.IDEMPLEADO = IDEMPLEADO;
                break;
            case "EDITAR":
                ModeloPdocs mdl;
                ControlPdocs ctrl = new ControlPdocs();
                mdl=ctrl.getRegistro(CONSULTA, ID);       
                this.txtIDPDOC.setText(""+mdl.getIDPDOC());
                this.txtIDPENDIENTE.setText(""+mdl.getIDPENDIENTE());
                this.txtCOMENTARIOS.setText(mdl.getCOMENTARIOS());
                this.lblARCHIVO.setText(mdl.getDOC());
                this.lblARCHIVO2.setText(mdl.getDOC());
                this.dteFECHA.setDate(G.formato.parse(mdl.getFECHA()));
                break;
            default:
                break;
        }
    }
       
    private void guardar(String ACCION) throws Exception
    {
        ModeloPdocs mdl = new ModeloPdocs();
        
        String DOC;
        mdl.setIDPENDIENTE(IDPENDIENTE);    
        mdl.setFECHA( G.formato.format(dteFECHA.getDate()));
        if(!lblARCHIVO.getText().equals("ARCHIVO"))
            DOC = lblARCHIVO.getText();
        else
            DOC = lblARCHIVO2.getText();
        mdl.setDOC(DOC);       
        mdl.setCOMENTARIOS(txtCOMENTARIOS.getText());
        
        switch(ACCION)
        {
            case "NUEVO":
                try
                {
                    IDPDOC = F.Registro("PDOCS", "IDPDOC", "DESC");
                    ControlPdocs ctrl = new ControlPdocs();
                    ctrl.guardarRegistro(mdl);                    
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                }
                break;
            case "EDITAR":
                try
                {
                    mdl.setIDPDOC(Integer.parseInt(String.valueOf(txtIDPDOC.getText())));
                    ControlPdocs cp = new ControlPdocs();
                    cp.actualizarRegistro(mdl);
                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }
        F.bitacora("PDOCS", IDPDOC, ACCION, G.IDUSER, ""+IDEMPLEADO, "");        
    }     
    
    
