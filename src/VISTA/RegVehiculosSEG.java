    public void mostrar(int IDVEHICULOSEG, int IDVEHICULO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;     
        this.IDVEHICULOSEG = IDVEHICULOSEG;
        
        vehiculo(IDVEHICULO);
        
        switch(ACCION)
        {
            case "NUEVO":
                lblIDVEHICULO.setText(""+IDVEHICULO);
                this.txtASEGURADORA.requestFocus();
                break;
            case "EDITAR":
                ModeloVehiculosSEG mdl;
                ControlVehiculosSEG ctrl = new ControlVehiculosSEG();
                mdl=ctrl.getRegistros(IDVEHICULOSEG);
                
                this.txtIDVEHICULOSEG.setText(""+mdl.getIDVEHICULOSEG());
                this.lblIDVEHICULO.setText(""+mdl.getIDVEHICULO());
                
                this.txtASEGURADORA.setText(""+mdl.getASEGURADORA());
                this.txtNP.setText(""+mdl.getNP());
                this.txtCOSTO.setText(""+mdl.getCOSTO());
                //this.lblEMPRESA.setSelectedItem(""+mdl.getEMPRESA());
                this.txtTITULAR.setText(""+mdl.getPROPIETARIO());
                this.lblARCHIVO.setText(""+mdl.getARCHIVO());
                this.dteINICIO.setDate(G.formato.parse(mdl.getFECHA()));
                this.dteFIN.setDate(G.formato.parse(mdl.getVIGENCIA()));
                
                break;
            default: break;
        }
    }
    
    private void vehiculo(int IDVEHICULO) throws ClassNotFoundException, SQLException, Exception
    {
        ModeloVehiculos mdl;
        ControlVehiculos ctrl = new ControlVehiculos();
        mdl=ctrl.getRegistros(IDVEHICULO);
        
        this.IDVEHICULO = IDVEHICULO;
        //this.lblEMPRESA.setText(""+mdl.getEMPRESA());
        this.txtEMPRESA.setSelectedItem(""+mdl.getEMPRESA());
        this.lblNOMBRE.setText(mdl.getMARCA()+" "+mdl.getMODELO());
    }
   
    private void guardar(String ACCION) throws Exception
    {
        ModeloVehiculosSEG mdl = new ModeloVehiculosSEG();
        
        mdl.setIDVEHICULO(IDVEHICULO);
        mdl.setASEGURADORA(txtASEGURADORA.getText());
        mdl.setNP(txtNP.getText());
        mdl.setPROPIETARIO(txtTITULAR.getText());
        mdl.setCOSTO(Float.parseFloat(txtCOSTO.getText()));       
        mdl.setFECHA(""+G.formato.format(dteINICIO.getDate()));
        mdl.setVIGENCIA(""+G.formato.format(dteFIN.getDate()));        
        mdl.setARCHIVO(lblARCHIVO.getText());
        mdl.setEMPRESA(txtEMPRESA.getSelectedItem().toString());
       
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            //IDVEHICULOSEG = F.Registro("VEHICULOSSEG","IDVEHICULOSEG","DESC");
                            //mdl.setIDVEHICULOSEG(IDVEHICULO);

                            ControlVehiculosSEG ctrl = new ControlVehiculosSEG();
                            ctrl.guardarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {                           
                            mdl.setIDVEHICULOSEG(Integer.parseInt(txtIDVEHICULOSEG.getText()));
                            ControlVehiculosSEG ctrl = new ControlVehiculosSEG();
                            ctrl.actualizarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default: 
                        break;
                }
        
        
    } 
    
