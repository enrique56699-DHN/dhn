    private String MOTIVOS()
    {
        String MOTIVOS = "";
        Component[] componentes = pnlMOTIVOS.getComponents();
        for (Component c : componentes) {
            if (c instanceof JCheckBox) {
                JCheckBox cb = (JCheckBox) c;
                // Comprobar si está seleccionado
                if (cb.isSelected()) {
                    MOTIVOS = MOTIVOS + cb.getText().toUpperCase()+" - ";
                }
            }
        }        
        return MOTIVOS;
    }

    private void guardar(String ACCION) throws ClassNotFoundException, SQLException, Exception
    { 
        if(!MOTIVOS().equals(""))
            F.bitacora("MOTIVOSR",IDNOTA,ACCION,G.IDUSER,"",MOTIVOS());
        else
            JOptionPane.showMessageDialog( null, "NO PUEDES GUARDAR REGISTRO SIN UN MOTIVO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
    }
    

