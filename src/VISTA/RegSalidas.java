    public void mostrar(int IDSALIDA, String ACCION, String DESCRIPCION) throws ParseException, ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        AUX="";
        switch(ACCION)
        {
            case "NUEVO":
                this.dte_fecha.setDate(G.hoy());
                //this.FECHA = G.FECHA(G.hoy(), true);
                this.txtDESCRIPCION.requestFocus();
                this.txtFAC.setVisible(false);
                break;
            case "EDITAR":
                ModeloSalidas pto;
                ControlSalidas cp = new ControlSalidas();
                pto=cp.getRegistrosID(IDSALIDA);                
                idsalidas = pto.getIDSALIDA();
                this.txtIDSALIDA.setText(""+pto.getIDSALIDA());
                this.txtDESCRIPCION.setText(""+pto.getDESCRIPCION());
                this.txtMONTO.setText(""+pto.getMONTO());
                this.dte_fecha.setDate(G.formato.parse(pto.getFECHA()));
                //this.FECHA = pto.getFECHA();
                this.IDCAJA = pto.getIDCAJA();
                this.txtFAC.setVisible(false);
                break;
            case "CONDONACION":
                this.AUX = ACCION;
                String []datos = DESCRIPCION.split("-");
                String []datos1 = DESCRIPCION.split(" ");
                this.IDNOTA = Integer.parseInt(datos1[2]);
                this.txtMETODO.setSelectedItem(datos[1]);
                this.txtMETODO.setEnabled(false);
                this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(datos[0]);
                //this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("CONDONACION");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("");
                this.txtMONTO.requestFocus();
                this.ACCION = "NUEVO";           
                this.txtFAC.setVisible(false);
                break;
            case "VEHICULOSSEG":
                this.AUX = ACCION;
                this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(DESCRIPCION);
                //this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("SEGUROS");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("");
                this.txtMONTO.requestFocus();
                this.ACCION = "NUEVO"; 
                this.txtFAC.setVisible(false);
                break;
            case "VEHICULOSSER":
                this.AUX = ACCION;
                this.dte_fecha.setDate(G.hoy());
                this.txtDESCRIPCION.setText(DESCRIPCION);
                //this.txtDESCRIPCION.requestFocus();
                this.txtCATEGORIA.setSelectedItem("MANTENIMIENTO DE VEHICULOS");
                this.txtCATEGORIA.setEnabled(false);
                this.dte_fecha.setEnabled(false);
                this.txtMONTO.setText("");
                this.txtMONTO.requestFocus();
                this.ACCION = "NUEVO";
                this.txtFAC.setVisible(false);
                break;
            case "CONCILIACION":
                this.AUX = ACCION;
                this.dte_fecha.setDate(G.hoy());
                this.dte_fecha.setEnabled(true);
                this.REF = DESCRIPCION;
                this.FAC = txtFAC.getText();
                this.ACCION = "NUEVO";
                this.txtFAC.setVisible(true);
                this.chkFAC.setVisible(true);
                this.chkPENDIENTE.setVisible(true);
                break;
            case "VALE":
                this.AUX = ACCION;
                this.ACCION = "NUEVO";
                this.txtDESCRIPCION.setText(DESCRIPCION);
                this.dte_fecha.setDate(G.hoy());
                this.dte_fecha.setEnabled(true);
                this.txtFAC.setVisible(false);
                this.chkPENDIENTE.setVisible(false);
                this.chkFAC.setVisible(false);
                this.txtMETODO.setSelectedItem("EFECTIVO");
                this.txtMETODO.setEnabled(false);   
                this.txtMONTO.requestFocus();
                break;
            default:
                break;
        }
        
    }
    
    private void guardar(String ACCION)
    {        
        if(this.txtDESCRIPCION.getText().equals(""))
        {
            JOptionPane.showMessageDialog( null, "CAMPO NO PUEDE ESTAR VACIO", "VERIFICAR", JOptionPane.WARNING_MESSAGE);
            this.txtDESCRIPCION.requestFocus();
        }
        else
        {
            ModeloSalidas md = new ModeloSalidas();
            
            md.setIDSALIDA (idsalidas);
            md.setDESCRIPCION(txtDESCRIPCION.getText());
            md.setMONTO(Float.parseFloat(txtMONTO.getText()));
            md.setCATEGORIA(txtCATEGORIA.getSelectedItem().toString());
            md.setMETODO(txtMETODO.getSelectedItem().toString());
            //md.setFECHA(G.formato.format(dte_fecha.getDate()));
            //this.FECHA = G.FECHA(dte_fecha.getDate(), true);
            md.setFECHA(G.FECHA(dte_fecha.getDate(), true));
            md.setIDCAJA(IDCAJA);
            switch(ACCION)
            {
                case "NUEVO":
                    try
                    {
                        idsalidas = F.Registro("SALIDAS","IDSALIDA","DESC");
                        md.setIDSALIDA(idsalidas);
                        
                        ControlSalidas cp = new ControlSalidas();
                        cp.guardarRegistro(md);
                        
                        switch(AUX)
                        {
                            case "CONDONACON":
                                ModeloPagos mdlP;
                                ControlPagos ctrlP = new ControlPagos();

                                mdlP = ctrlP.getRegistrosIDR(IDNOTA);
                                String COMENTARIOS = mdlP.getCOMENTARIOS()+"-"+"PAGO CONDONADO SALIDA "+idsalidas;

                                ControlPagos ctrlP1;
                                ctrlP1 = new ControlPagos();
                                ctrlP1.actualizarComentarios(COMENTARIOS, IDNOTA);  
                                break;
                            case "CONCILIACION":
                                ModeloMovD mdl = new ModeloMovD();        
                                
                                /*int IDMOVD = F.Registro("MOVD","IDMOVD","DESC");
                                mdl.setIDMOVD(IDMOVD);*/

                                mdl.setIDMOVIMIENTO(idsalidas);
                                mdl.setMOVIMIENTO("SALIDAS");
                                mdl.setREF(REF);
                                mdl.setCOTEJADO(false);
                                mdl.setFAC(txtFAC.getText());
                                
                                ControlMovD ctrlMD = new ControlMovD();
                                ctrlMD.guardarRegistro(mdl);
                                break;                            
                            default:
                                break;
                        }
                        /*if(AUX.equals("CONDONACION"))
                        {
                            ModeloPagos mdlP;
                            ControlPagos ctrlP = new ControlPagos();
                            
                            mdlP = ctrlP.getRegistrosIDR(IDNOTA);
                            String COMENTARIOS = mdlP.getCOMENTARIOS()+"-"+"PAGO CONDONADO SALIDA "+idsalidas;
                            
                            ControlPagos ctrlP1;
                            ctrlP1 = new ControlPagos();
                            ctrlP1.actualizarComentarios(COMENTARIOS, IDNOTA);                       
                        }*/
                        
                        APOYO();
                        this.dispose();
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO "+ex, "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                case "EDITAR":
                    try
                    {
                        ControlSalidas cp = new ControlSalidas();
                        cp.actualizarRegistro(md);
                        APOYO();
                        this.dispose();
                    }
                    catch (Exception ex)
                    {
                        JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                    }
                    break;
                default:
                    break;
            }
        }
         
    }
    
    private void APOYO() throws SQLException, Exception
    {
        JInternalFrame ji = validador.getJInternalFrame(VApoyo.class.getName());
        if(ji != null )
            ji.dispose();
        ji = new VApoyo("SALIDA",G.formato.format(dte_fecha.getDate()),""+idsalidas,""+G.numero.format(Float.parseFloat(txtMONTO.getText()))+".00",txtDESCRIPCION.getText(),txtCATEGORIA.getSelectedItem().toString());
        Principal.getCONT().add(ji);
        validador.addJIframe(VApoyo.class.getName(), ji);
        RegSalidas.btnCERRAR.doClick();
        this.dispose();
            ji.setMaximum(true);        
    }
    
