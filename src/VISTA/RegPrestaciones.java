    public void mostrar(int IDPRESTACION, String ACCION, String CONCEPTO) throws ParseException, ClassNotFoundException, Exception
    {
        if("NUEVO".equals(ACCION))
        {
            this.IDPRESTACION = IDPRESTACION-1;
        }
        else
            this.IDPRESTACION = IDPRESTACION;
        
        this.ACCION = ACCION;
        this.CONCEPTO = CONCEPTO;
        this.txtCONCEPTO.setText(CONCEPTO);
        this.txtIDPRESTACION.setText(""+IDPRESTACION);
        this.txtCONCEPTO.setText(""+CONCEPTO);
        
        ModeloPrestaciones mdl;
        ControlPrestaciones ctrl = new ControlPrestaciones();
        mdl=ctrl.getRegistrosID(this.IDPRESTACION);
        
        if("".equals(mdl.getFINI()))
        {
            FINI=G.FECHA(G.hoy(),false);
        }
        else
            FINI=mdl.getFINI();
        
        if("".equals(mdl.getFFIN()))
        {
            FFIN=G.FECHA(G.hoy(),false);
        }
        else
            FFIN=mdl.getFFIN();
        
        ESTADO=mdl.getESTADO();
        PERIODO=mdl.getPERIODO();
        
        switch(ACCION)
        {
            case "NUEVO":
                int ultimo = ControlPrestaciones.Registro(CONCEPTO, "DESC");
                this.txtPERIODO.setText(""+ultimo);
                NFINI=G.formato.parse(FINI);
                Calendar calendar = Calendar.getInstance();
                calendar.setTime(NFINI);
                calendar.add(Calendar.YEAR,+1);
                NFINI=calendar.getTime();
                dteFINI.setDate(NFINI);
                
                NFFIN=G.formato.parse(FFIN);
                Calendar calendar1 = Calendar.getInstance();
                calendar1.setTime(NFFIN);
                calendar1.add(Calendar.YEAR,+1);
                NFFIN=calendar1.getTime();
                dteFFIN.setDate(NFFIN);
                
                break;
            case "EDITAR":
                dteFINI.setDate(G.formato.parse(FINI));
                dteFFIN.setDate(G.formato.parse(FFIN));
                if("SELECCIONADO".equals(ESTADO))
                {
                    chkSELECCIONAR.setSelected(true);
                }
                this.txtPERIODO.setText(""+PERIODO);
                break;
                
                
                
            default: break;                
        }
    }
    
    private void guardar(String ACCION)
    {
        ModeloPrestaciones md = new ModeloPrestaciones();
        md.setIDPRESTACION(Integer.parseInt(txtIDPRESTACION.getText()));
        md.setCONCEPTO(CONCEPTO);
        md.setPERIODO(Integer.parseInt(txtPERIODO.getText()));
        md.setFINI(G.formato.format(dteFINI.getDate()));
        md.setFFIN(G.formato.format(dteFFIN.getDate()));
        md.setESTADO("");
        
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {

                            ControlPrestaciones cp = new ControlPrestaciones();
                            cp.guardarRegistro(md);
                            JOptionPane.showMessageDialog( null, "REGISTRO GUARDADO CORRECTAMENTE", "GUARDANDO", JOptionPane.INFORMATION_MESSAGE);
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {
                            ControlPrestaciones cp = new ControlPrestaciones();
                            cp.actualizarRegistro(md);
                            JOptionPane.showMessageDialog( null, "REGISTRO ACTUALIZADO CORRECTAMENTE", "ACTUALIZANDO", JOptionPane.INFORMATION_MESSAGE);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default: break;
                }
    }
    
