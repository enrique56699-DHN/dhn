    public void mostrar(int IDPENDIENTE, int IDCLIENTE, String ACCION, String CATEGORIA, String DESCRIPCION, int opn) throws ParseException, Exception
    {
        this.ACCION = ACCION;
        this.IDPENDIENTE = IDPENDIENTE;        
        
        switch(ACCION)
        {
            case "NUEVO":
                switch(CATEGORIA)
                {
                    case "INTERNET":
                        this.IDCONTRATO = IDCLIENTE;
                        ModeloContratos mdlC;
                        ControlContratos ctrlC = new ControlContratos();
                        mdlC = ctrlC.getRegistrosID(IDCONTRATO);

                        this.IDCLIENTE = mdlC.getIDCLIENTE();
                        this.IDDIR = mdlC.getIDDIRECCION();
                        cliente(this.IDCLIENTE);
                        direcciones(this.IDCLIENTE,IDDIR);
                        this.txtDESCRIPCION.setText("CONTRATO N: "+IDCONTRATO+"\n"+DESCRIPCION);
                        this.txtCATEGORIA.setSelectedItem(CATEGORIA);
                        //this.CATEGORIA2 = CATEGORIA;
                        this.txtNPEDIDO.setText("DHN-"+opn+"-"+IDCONTRATO);
                        this.txtCOMENTARIOS.requestFocus();
                        break;
                    case "HVAC":
                        this.IDCLIENTE = IDCLIENTE;
                        cliente(IDCLIENTE);
                        direcciones(IDCLIENTE,0);
                        this.txtDESCRIPCION.setText(DESCRIPCION);
                        this.txtCATEGORIA.setSelectedItem("VENTA");

                        this.txtCOMENTARIOS.requestFocus();
                        //search();
                        break;
                    case "SERVICIO":
                        this.IDCLIENTE = IDCLIENTE;
                        cliente(IDCLIENTE);
                        direcciones(IDCLIENTE,0);
                        this.txtDESCRIPCION.requestFocus();
                        break;
                    default:
                        
                        break;
                }                                
                break;
            case "EDITAR":
                ModeloPendientes pto;
                ControlPendientes cp = new ControlPendientes();
                pto=cp.getRegistrosID(IDPENDIENTE);
                
                this.IDCLIENTE= IDCLIENTE;
                txtNPENDIENTE.setText(""+IDPENDIENTE);
                detREGISTRO.setDate(G.formato.parse(pto.getFREG()));
                //ID=pto.getIDCLIENTE();
                this.IDDIR=pto.getIDDIRECCION();
                this.txtCOMENTARIOS.setText(""+pto.getCOMENTARIOS());
                this.txtDESCRIPCION.setText(""+pto.getDESCRIPCION());
                this.ESTADO=pto.getESTADO();
                this.txtNPEDIDO.setText(""+pto.getNPEDIDO());
                this.txtNPEDIDOF.setText(""+pto.getNPEDIDOF());
                this.txtCATEGORIA.setSelectedItem(pto.getCATEGORIA());
                FEST=pto.getFEST();        
                if(!FEST.equals(""))
                {
                    this.dte_ESTIMADA.setDate(G.formato.parse(FEST));
                }
                FFIN=pto.getFFIN();
                if(!FFIN.equals(""))
                {
                    this.dte_FIN.setDate(G.formato.parse(FFIN));
                }
                direcciones(IDCLIENTE,IDDIR);
                
                break;
            default:
                break;
        }        
        
    }
    
    private void guardar(String ACCION) throws SQLException, Exception
    {
        ModeloPendientes x = new ModeloPendientes();

        x.setIDPENDIENTE(IDPENDIENTE);
        
        x.setIDCLIENTE(IDCLIENTE);
        x.setIDDIRECCION(IDDIRECCION(IDCLIENTE));
        x.setNPEDIDO(txtNPEDIDO.getText());
        x.setNPEDIDOF(txtNPEDIDOF.getText());
        x.setCATEGORIA(txtCATEGORIA.getSelectedItem().toString());        
        x.setSUBCATEGORIA("GENERAL");        
        DESCRIPCION = txtDESCRIPCION.getText().toUpperCase();
        x.setDESCRIPCION(DESCRIPCION);     
        COMENTARIOS = txtCOMENTARIOS.getText().toUpperCase();
        x.setCOMENTARIOS(COMENTARIOS);   
        x.setFREG(""+G.formato.format(detREGISTRO.getDate()));
        
        if(dte_ESTIMADA.getDate()==null)        
            x.setFEST("");
        else
            x.setFEST(""+G.formato.format(dte_ESTIMADA.getDate()));
        
        if(dte_FIN.getDate()==null)
            x.setFFIN("");
        else
            x.setFFIN(""+G.formato.format(dte_FIN.getDate()));
        
        x.setESTADO(ESTADO);
        
        switch(ACCION)
        {
            case "NUEVO":
                try
                { 
                    IDPENDIENTE = F.Registro("PENDIENTES","IDPENDIENTE","DESC");
                    x.setIDPENDIENTE(IDPENDIENTE);
                    ESTADO = "ABIERTO";
                    x.setESTADO(ESTADO);
                    
                    ControlPendientes cp = new ControlPendientes();
                    cp.guardarRegistro(x);
                    if(txtCATEGORIA.getSelectedItem().toString().equals("SERVICIO"))
                    {
                        ModeloCarrito mdl = new ModeloCarrito();
                        mdl.setIDCARRITO(F.Registro("CARRITO","IDCARRITO","DESC"));
                        mdl.setIDPENDIENTE(IDPENDIENTE);
                        mdl.setIDPRODUCTO(108);
                        mdl.setCANTIDAD(1);
                        mdl.setTOTAL(350);
                        mdl.setESTADO("PENDIENTE");
                        mdl.setIDEMPLEADO(0);
                        mdl.setFECHA(FEST);
                        
                        ControlCarrito ctrl = new ControlCarrito();
                        ctrl.guardarRegistro(mdl);
                    }

                    this.dispose();
                }
                catch (Exception ex)
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            case "EDITAR":
                try
                {
                    ControlPendientes cp = new ControlPendientes();
                    cp.actualizarRegistro(x);
                    this.dispose();
                } 
                catch (Exception ex) 
                {
                    JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                }
                break;
            default:
                break;
        }
        F.bitacora("PENDIENTES",IDPENDIENTE,ACCION,G.IDUSER,COMENTARIOS,DESCRIPCION);
        
        btnGUARDAR.setEnabled(true);
    }
  
