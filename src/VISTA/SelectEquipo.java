    public void mostrar(int IDCONTRATO) throws ClassNotFoundException, Exception
    {
        this.IDCONTRATO = IDCONTRATO;
        ModeloContratos mdl;
        ControlContratos ctrl = new ControlContratos();
        mdl = ctrl.getRegistrosIDINNER(IDCONTRATO);        
        this.lblNOMBRE.setText(mdl.getNOMBRE());
        this.lblIDCONTRATO.setText(""+IDCONTRATO);
        this.lblDOMICILIO.setText(mdl.getCALLE()+" "+mdl.getNUMERO()+" "+mdl.getCOLONIA()+" "+mdl.getLOCALIDAD());
        this.txtIP.setText(mdl.getIP());
        this.txtEQUIPO.setSelectedItem(mdl.getEQUIPO());
        this.txtIP.selectAll();
        this.txtIP.setText("");
    }
    
    
    private void agregar() throws SQLException, Exception
    {
        ControlContratos ctrl = new ControlContratos();        
        ctrl.actualizarEQUIPO(IDCONTRATO, txtEQUIPO.getSelectedItem().toString(), txtIP.getText());
    }
    
