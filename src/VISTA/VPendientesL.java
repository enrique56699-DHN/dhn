    private void permisos(String PRIVILEGIOS)
    {
        if(PRIVILEGIOS.equals("SADMIN"))
        {
            btnEDITAR.setEnabled(true);
        }
    }

    private void editar() throws Exception
    {
        ModeloPendientes mdl;
        ControlPendientes ctrl = new ControlPendientes();
        mdl = ctrl.getRegistrosID(IDPENDIENTE);
        int IDCLIENTE = mdl.getIDCLIENTE();
        RegPendientes p = new RegPendientes(null,true);
        p.mostrar(IDPENDIENTE,IDCLIENTE,"EDITAR",null, null, 0);
        p.setVisible(true);
        
    }
    
    private void actualizarTablas(String CATEGORIA, String ESTADO) throws ClassNotFoundException, SQLException
    {
        ModeloPendientesTabla mtp;
        mtp = new ModeloPendientesTabla(CATEGORIA, ESTADO);
        jtblPENDIENTES.setModel(mtp);
        mtp.fireTableDataChanged();
        F.dimensionar(jtblPENDIENTES,"PENDIENTES");
    }
 
    private void seleccion() throws ClassNotFoundException, SQLException, Exception
    {
        int fila = jtblPENDIENTES.getSelectedRow();
        IDPENDIENTE = (int) jtblPENDIENTES.getValueAt(fila, 0);
    }
            
    private void abrir(int ID, int IDORDEN) throws ParseException, Exception
    {
        RegOrdenesPD reg;            
        reg = new RegOrdenesPD(null,true);
        reg.mostrar(ID,IDORDEN);
        reg.setVisible(true);
            
    }
    
    private void codigo() throws ParseException
    {
        LeerQR reg;            
        reg = new LeerQR(null,true);
        reg.setVisible(true);
    }
    
    private void agenda() throws ClassNotFoundException, SQLException, Exception
    {
        JInternalFrame ji = validador.getJInternalFrame(VAgendaL.class.getName());
        if(ji != null )
            ji.dispose();
        try {               
            ji = new VAgendaL("Agenda de Servicios");
            Principal.getCONT().add(ji);
            validador.addJIframe(VAgendaL.class.getName(), ji);
        } catch (ParseException ex) {
            Logger.getLogger(VPendientesL.class.getName()).log(Level.SEVERE, null, ex);
        } catch (Exception ex) {
            Logger.getLogger(VPendientesL.class.getName()).log(Level.SEVERE, null, ex);
        }
        try {
            ji.setMaximum(true);
        } catch (PropertyVetoException ex) {
            Logger.getLogger(VPendientesL.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        ji.setVisible(true);
        ji.moveToFront();
        this.setClosed(true);
        this.dispose();
        
    }
    
