    public void mostrar(int IDEDOC, int IDEMPLEADO, String ACCION) throws ClassNotFoundException, SQLException, Exception
    {
        this.ACCION = ACCION;
        this.IDEDOC = IDEDOC;
        this.IDEMPLEADO = IDEMPLEADO;
        
        switch(ACCION)
        {
            case "NUEVO":
                this.txtNUMERO.requestFocus();
                break;
            case "EDITAR":
                ModeloEDocs pto;
                ControlEDocs ca = new ControlEDocs();
                pto=ca.getRegistro(IDEDOC);
                
                this.txtID.setText(""+pto.getIDEDOC());
                this.txtDESCRIPCION.setSelectedItem(pto.getDESCRIPCION());
                this.txtNUMERO.setText(""+pto.getNUMBER());
                this.lblARCHIVO.setText(pto.getDOC());
                this.dteVIGENCIA.setDate(G.formato.parse(pto.getVIGENCIA()));
                break;
            default: break;
        }
    }
   
    private void cmb() throws ClassNotFoundException, SQLException
    {
        txtDESCRIPCION.removeAllItems();        
        String TABLA = "EDOCS";        
        //int NUM = mdlt.getRowCount();
        mdlt = new ModeloDetallesDispTabla(TABLA,"DOCUMENTOS");
        for(int i=0;i<mdlt.getRowCount();i++)
        {
            txtDESCRIPCION.addItem((String) mdlt.getValueAt(i, 0));            
        }        
        
    }   
    
    private void guardar(String ACCION) throws Exception
    {
        ModeloEDocs mdl = new ModeloEDocs();
        
        mdl.setDESCRIPCION(txtDESCRIPCION.getSelectedItem().toString());
        mdl.setNUMBER(txtNUMERO.getText());
        mdl.setIDEMPLEADO(IDEMPLEADO);        
        mdl.setDOC(this.lblARCHIVO.getText());
        mdl.setVIGENCIA( G.formato.format(dteVIGENCIA.getDate()));
        
        switch(ACCION)
                {
                    case "NUEVO":
                        try
                        {
                            //IDANTENA = F.Registro("ANTENAS","IDANTENA","DESC");
                            //antenas.setIDANTENA(IDANTENA);

                            ControlEDocs cp = new ControlEDocs();
                            cp.guardarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR GUARDAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);

                        }
                        break;
                    case "EDITAR":
                        try
                        {
                            mdl.setIDEDOC(Integer.parseInt(String.valueOf(txtID.getText())));
                            ControlEDocs cp = new ControlEDocs();
                            cp.actualizarRegistro(mdl);
                            this.dispose();
                        }
                        catch (Exception ex)
                        {
                            JOptionPane.showMessageDialog( null, "ERROR AL INTENTAR ACTUALIZAR EL REGISTRO", "VERIFICAR", JOptionPane.ERROR_MESSAGE);
                        }
                        break;
                    default: break;
                }
        
        
    }     
    
